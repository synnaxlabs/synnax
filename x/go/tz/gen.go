func main() {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatal(err)
	}
	src := filepath.Join(strings.TrimSpace(string(out)), "lib", "time", "zoneinfo.zip")
	data, err := os.ReadFile(src)
	if err != nil {
		log.Fatal(err)
	}
	r, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		log.Fatal(err)
	}
	files := slices.Clone(r.File)
	slices.SortFunc(
		files,
		func(a, b *zip.File) int { return strings.Compare(a.Name, b.Name) },
	)
	for _, name := range focusZones {
		if !slices.ContainsFunc(
			files,
			func(f *zip.File) bool { return f.Name == name },
		) {
			log.Fatalf("focus zone %q is not in the zone database", name)
		}
	}
	write("zoneinfo.gen.go", goData(data))
	write(filepath.Join("..", "..", "cpp", "tz", "zoneinfo.inc"), cppData(files))
	write(filepath.Join("testdata", "vectors.tsv"), zoneVectors(files))
	write(filepath.Join("testdata", "rules.tsv"), ruleVectors())
}

func write(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
}

// goData returns a Go file holding the zone database as a base64 constant, as Go's
// time/tzdata package does.
func goData(data []byte) string {
	var b strings.Builder
	b.WriteString(copyright)
	b.WriteString("// Code generated by gen.go. DO NOT EDIT.\n\n")
	b.WriteString("package tz\n\n")
	b.WriteString(
		"// zoneinfo is the Go toolchain's zone database, a zip of TZif files, in ",
	)
	b.WriteString("base64.\n")
	b.WriteString("const zoneinfo = \"\" +\n")
	encoded := base64.StdEncoding.EncodeToString(data)
	for i := 0; i < len(encoded); i += 76 {
		fmt.Fprintf(&b, "\t%q +\n", encoded[i:min(i+76, len(encoded))])
	}
	b.WriteString("\t\"\"\n")
	return b.String()
}

// cppData returns the zone database as C++ arrays for x/cpp/tz.
func cppData(files []*zip.File) string {
	var data, entries strings.Builder
	offset := 0
	line := 0
	for _, f := range files {
		content := read(f)
		fmt.Fprintf(&entries, "    {\"%s\", %d, %d},\n", f.Name, offset, len(content))
		offset += len(content)
		for _, c := range content {
			n := fmt.Sprintf("%d,", c)
			if line+len(n) > 84 {
				data.WriteString("\n")
				line = 0
			}
			if line == 0 {
				data.WriteString("    ")
				line = 4
			}
			data.WriteString(n)
			line += len(n)
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by x/go/tz/gen.go. DO NOT EDIT.\n\n")
	b.WriteString("constexpr unsigned char DATA[] = {\n")
	b.WriteString(data.String())
	b.WriteString("\n};\n\nconstexpr Entry ENTRIES[] = {\n")
	b.WriteString(entries.String())
	b.WriteString("};\n")
	return b.String()
}

// zoneVectors returns Go's offset and abbreviation for every zone at the sample,
// random, and transition instants.
func zoneVectors(files []*zip.File) string {
	var b strings.Builder
	b.WriteString("# Generated by gen.go. DO NOT EDIT.\n")
	b.WriteString("# zone\tunix seconds\toffset seconds\tabbreviation\n")
	// A fixed seed keeps go generate output stable.
	random := rand.New(rand.NewPCG(5006, 0))
	for _, f := range files {
		loc, err := time.LoadLocationFromTZData(f.Name, read(f))
		if err != nil {
			log.Fatal(err)
		}
		secs := append(sampleSeconds(), randomSeconds(random)...)
		if slices.Contains(focusZones, f.Name) {
			secs = append(secs, transitionSeconds(loc)...)
		}
		slices.Sort(secs)
		for _, sec := range slices.Compact(secs) {
			name, offset := time.Unix(sec, 0).In(loc).Zone()
			fmt.Fprintf(&b, "%s\t%d\t%d\t%s\n", f.Name, sec, offset, name)
		}
	}
	return b.String()
}

// randomSeconds returns 10 instants across the timestamp range and 10 from 1900 to
// 2100.
func randomSeconds(random *rand.Rand) []int64 {
	const first, last = -9_223_372_037, 9_223_372_036
	start := time.Date(1900, time.January, 1, 0, 0, 0, 0, time.UTC).Unix()
	stop := time.Date(2100, time.January, 1, 0, 0, 0, 0, time.UTC).Unix()
	secs := make([]int64, 0, 20)
	for range 10 {
		secs = append(secs, first+random.Int64N(last-first+1))
		secs = append(secs, start+random.Int64N(stop-start))
	}
	return secs
}

func read(f *zip.File) []byte {
	rc, err := f.Open()
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = rc.Close() }()
	data, err := io.ReadAll(rc)
	if err != nil {
		log.Fatal(err)
	}
	return data
}

