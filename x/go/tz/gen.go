// ruleVectors returns Go's answers for each synthetic rule zone around every change in
// 1960, 2023 to 2025, and 2261.
func ruleVectors() string {
	var b strings.Builder
	b.WriteString("# Generated by gen.go. DO NOT EDIT.\n")
	b.WriteString("# rule\tunix seconds\toffset seconds\tabbreviation\n")
	for _, rule := range rules {
		loc, err := time.LoadLocationFromTZData("rule", RuleZone(rule))
		if err != nil {
			log.Fatal(err)
		}
		var secs []int64
		for _, year := range []int{1960, 2023, 2024, 2025, 2261} {
			for month := time.January; month <= time.December; month++ {
				secs = append(
					secs,
					time.Date(year, month, 1, 12, 0, 0, 0, time.UTC).Unix(),
				)
			}
			start := time.Date(year, time.January, 1, 0, 0, 0, 0, time.UTC)
			secs = append(
				secs,
				transitionsBetween(loc, start, start.AddDate(1, 0, 0))...,
			)
		}
		slices.Sort(secs)
		for _, sec := range slices.Compact(secs) {
			name, offset := time.Unix(sec, 0).In(loc).Zone()
			fmt.Fprintf(&b, "%s\t%d\t%d\t%s\n", rule, sec, offset, name)
		}
	}
	return b.String()
}

// RuleZone returns TZif data for a zone with no transitions and rule as its rule
// string.
func RuleZone(rule string) []byte {
	var b bytes.Buffer
	header := func(types, chars uint32) {
		b.WriteString("TZif2")
		b.Write(make([]byte, 15))
		for _, n := range []uint32{0, 0, 0, 0, types, chars} {
			_ = binary.Write(&b, binary.BigEndian, n)
		}
	}
	header(0, 0)
	header(1, 4)
	_ = binary.Write(&b, binary.BigEndian, int32(3600))
	b.Write([]byte{0, 0})
	b.WriteString("FAL\x00")
	b.WriteString("\n" + rule + "\n")
	return b.Bytes()
}

// sampleSeconds are the instants every zone is checked at.
func sampleSeconds() []int64 {
	day := func(year int, month time.Month) int64 {
		return time.Date(year, month, 15, 12, 0, 0, 0, time.UTC).Unix()
	}
	return []int64{
		-9_223_372_037,
		9_223_372_036,
		0,
		day(1900, time.July),
		day(2026, time.January),
		day(2026, time.July),
		day(2100, time.January),
		day(2100, time.July),
		day(2200, time.July),
	}
}

// transitionSeconds returns the second before and the second of each zone change
// from 1900 to 2100.
func transitionSeconds(loc *time.Location) []int64 {
	return transitionsBetween(
		loc,
		time.Date(1900, time.January, 1, 0, 0, 0, 0, time.UTC),
		time.Date(2100, time.January, 1, 0, 0, 0, 0, time.UTC),
	)
}

// transitionsBetween returns the second before and the second of each zone change
// from start until stop.
func transitionsBetween(loc *time.Location, start, stop time.Time) []int64 {
	var secs []int64
	t := start.In(loc)
	for t.Before(stop) {
		_, end := t.ZoneBounds()
		if end.IsZero() {
			break
		}
		// Go ends a daylight rule year at day 365, short of a leap year's end.
		if !end.After(t) {
			t = t.Add(24 * time.Hour)
			continue
		}
		before, _ := end.Add(-time.Second).Zone()
		after, _ := end.Zone()
		_, beforeOffset := end.Add(-time.Second).Zone()
		_, afterOffset := end.Zone()
		if before != after || beforeOffset != afterOffset {
			secs = append(secs, end.Unix()-1, end.Unix())
		}
		t = end
	}
	return secs
}
