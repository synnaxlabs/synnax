import subprocess

import pytest
from conftest import CopyrightRepo

ORACLE = "// Code generated by oracle. DO NOT EDIT.\n\npackage x\n"
STRINGER = '// Code generated by "stringer -type=Kind"; DO NOT EDIT.\n\npackage x\n'
TOOL = "// Code generated by gen.go. DO NOT EDIT.\n\npackage x\n"
TEMPLATE = 'var t = "// Code generated by oracle. DO NOT EDIT."\n'


def check(repo: CopyrightRepo) -> subprocess.CompletedProcess[str]:
    return repo.run("bash", "scripts/check_copyrights.sh", "src")


@pytest.fixture
def repo(copyright_repo: CopyrightRepo) -> CopyrightRepo:
    (copyright_repo.path / "src").mkdir()
    return copyright_repo


class TestCheckCopyrights:
    """Runs check_copyrights.sh on Oracle outputs and other files."""

    @pytest.mark.parametrize(
        ("name", "body"),
        [
            ("src/a.pb.go", "package x\n"),
            ("src/a.gen.go", ORACLE),
            ("src/a_gen_test.go", ORACLE),
        ],
    )
    def test_should_accept_a_past_year_in_an_oracle_output(
        self, repo: CopyrightRepo, name: str, body: str
    ) -> None:
        repo.write(name, repo.year - 3, body)
        result = check(repo)
        assert result.returncode == 0, result.stdout

    @pytest.mark.parametrize(
        ("name", "body"),
        [
            ("src/a.go", "package x\n"),
            ("src/a.go", TEMPLATE),
            ("src/kind_string.go", STRINGER),
            ("src/zoneinfo.gen.go", TOOL),
        ],
    )
    def test_should_reject_a_past_year_in_any_other_file(
        self, repo: CopyrightRepo, name: str, body: str
    ) -> None:
        repo.write(name, repo.year - 3, body)
        result = check(repo)
        assert result.returncode == 1
        assert "incorrect copyright year" in result.stdout

    def test_should_reject_a_future_year_in_an_oracle_output(
        self, repo: CopyrightRepo
    ) -> None:
        repo.write("src/a.gen.go", repo.year + 1, ORACLE)
        result = check(repo)
        assert result.returncode == 1
        assert "incorrect copyright year" in result.stdout

    def test_should_accept_the_current_year_in_a_hand_written_file(
        self, repo: CopyrightRepo
    ) -> None:
        repo.write("src/a.go", repo.year)
        result = check(repo)
        assert result.returncode == 0, result.stdout
