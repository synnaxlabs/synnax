import subprocess

import pytest
from conftest import CopyrightRepo

BANNER = "// Code generated by oracle. DO NOT EDIT.\n\npackage x\n"
TEMPLATE = 'var t = "// Code generated by oracle. DO NOT EDIT."\n'


def check(repo: CopyrightRepo) -> subprocess.CompletedProcess[str]:
    return repo.run("bash", "scripts/check_copyrights.sh", "src")


@pytest.fixture
def repo(copyright_repo: CopyrightRepo) -> CopyrightRepo:
    (copyright_repo.path / "src").mkdir()
    return copyright_repo


class TestCheckCopyrights:
    """Runs check_copyrights.sh on generated and hand-written files."""

    @pytest.mark.parametrize(
        ("name", "body"),
        [
            ("src/a.gen.go", "package x\n"),
            ("src/a.pb.go", "package x\n"),
            ("src/a_gen_test.go", BANNER),
        ],
    )
    def test_should_accept_a_past_year_in_a_generated_file(
        self, repo: CopyrightRepo, name: str, body: str
    ) -> None:
        repo.write(name, repo.year - 3, body)
        result = check(repo)
        assert result.returncode == 0, result.stdout

    @pytest.mark.parametrize("body", ["package x\n", TEMPLATE])
    def test_should_reject_a_past_year_in_a_hand_written_file(
        self, repo: CopyrightRepo, body: str
    ) -> None:
        repo.write("src/a.go", repo.year - 3, body)
        result = check(repo)
        assert result.returncode == 1
        assert "incorrect copyright year" in result.stdout

    def test_should_reject_a_future_year_in_a_generated_file(
        self, repo: CopyrightRepo
    ) -> None:
        repo.write("src/a.gen.go", repo.year + 1)
        result = check(repo)
        assert result.returncode == 1
        assert "incorrect copyright year" in result.stdout

    def test_should_accept_the_current_year_in_a_hand_written_file(
        self, repo: CopyrightRepo
    ) -> None:
        repo.write("src/a.go", repo.year)
        result = check(repo)
        assert result.returncode == 0, result.stdout
