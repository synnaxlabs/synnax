from conftest import GitRepo

from check_suppressions_py import check, check_source

SOURCE = """from typing import cast
from typing import cast as c
import typing
import typing_extensions as te

a = f()  # type: ignore[arg-type]
b = g()  # noqa: E501
c2 = h()  # pyright: ignore
d = cast(int, a)
e = typing.cast(int, b)
f2 = c(int, b)
g2 = te.cast(int, b)
h = wrap_cast(c2)
i = arr.cast(d)
j = "x  # type: ignore"
k1 = 1  # ruff: noqa: E501
k2 = 1  # flake8: noqa
k3 = 1  # NOQA
k4 = 1  # mypy: ignore-errors
k5 = 1  # mypy: disable-error-code="arg-type"
k6 = 1  # pyright: basic
k7 = 1  # pyright: reportGeneralTypeIssues=false


def cast(x: int) -> int:
    return x
"""


class TestCheckSource:
    def test_should_report_each_suppression(self) -> None:
        lines = [f.line for f in check_source(SOURCE, path="a.py")]
        assert lines == [6, 7, 8, 9, 10, 11, 12, *range(16, 23)]

    def test_should_report_each_type_checking_use(self) -> None:
        source = (
            "import typing\n"
            "from typing import TYPE_CHECKING\n"
            "if TYPE_CHECKING:\n"
            "    pass\n"
            "if typing.TYPE_CHECKING:\n"
            "    pass\n"
            'NAME = "TYPE_CHECKING"\n'
        )
        findings = check_source(source, path="a.py")
        assert [f.line for f in findings] == [2, 3, 5]
        assert all("TYPE_CHECKING" in f.message for f in findings)

    def test_should_skip_generated_files(self) -> None:
        source = "# Code generated by oracle. DO NOT EDIT.\nx = 1  # type: ignore\n"
        assert check_source(source, path="a.py") == []

    def test_should_check_files_that_quote_the_banner(self) -> None:
        source = 'BANNER = "# Code generated by oracle."\nx = 1  # type: ignore\n'
        assert [f.line for f in check_source(source, path="a.py")] == [2]


class TestCheck:
    def test_should_report_tracked_and_untracked_files(self, git_repo: GitRepo) -> None:
        tmp_path = git_repo.path
        git_repo.commit({"a.py": "x = 1\ny = g()  # type: ignore\n", "b.py": "z = 1\n"})
        (tmp_path / "c.py").write_text("z = 1  # noqa\n")
        findings = check(root=tmp_path)
        assert [(f.path, f.line) for f in findings] == [("a.py", 2), ("c.py", 1)]

    def test_should_check_files_with_non_ascii_names(self, git_repo: GitRepo) -> None:
        git_repo.commit({"données.py": "x = 1  # noqa\n"})
        assert [f.path for f in check(root=git_repo.path)] == ["données.py"]

    def test_should_skip_ignored_and_deleted_files(self, git_repo: GitRepo) -> None:
        tmp_path = git_repo.path
        git_repo.commit({".gitignore": "ignored.py\n", "gone.py": "x = 1  # noqa\n"})
        (tmp_path / "gone.py").unlink()
        (tmp_path / "ignored.py").write_text("x = 1  # noqa\n")
        assert check(root=tmp_path) == []
