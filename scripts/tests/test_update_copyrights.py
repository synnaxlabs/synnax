import pytest
from conftest import CopyrightRepo

BANNER = "// Code generated by oracle. DO NOT EDIT.\n\npackage x\n"
TEMPLATE = 'var t = "// Code generated by oracle. DO NOT EDIT."\n'


class TestUpdateCopyrights:
    """Runs update_copyrights.sh on generated and hand-written files."""

    @pytest.mark.parametrize(
        ("name", "body"),
        [
            ("a.gen.go", "package x\n"),
            ("a.pb.go", "package x\n"),
            ("a_gen_test.go", BANNER),
        ],
    )
    def test_should_keep_a_past_year_in_a_generated_file(
        self, copyright_repo: CopyrightRepo, name: str, body: str
    ) -> None:
        past = copyright_repo.year - 3
        copyright_repo.write(name, past, body)
        before = (copyright_repo.path / name).read_text()
        result = copyright_repo.run("bash", "scripts/update_copyrights.sh", name)
        assert result.returncode == 0, result.stderr
        assert "Skipped 1 file" in result.stdout
        assert (copyright_repo.path / name).read_text() == before

    @pytest.mark.parametrize("body", ["package x\n", TEMPLATE])
    def test_should_set_the_current_year_in_a_hand_written_file(
        self, copyright_repo: CopyrightRepo, body: str
    ) -> None:
        copyright_repo.write("a.go", copyright_repo.year - 3, body)
        result = copyright_repo.run("bash", "scripts/update_copyrights.sh", "a.go")
        assert result.returncode == 0, result.stderr
        assert copyright_repo.year_of("a.go") == copyright_repo.year

    def test_should_set_the_current_year_for_a_future_year_in_a_generated_file(
        self, copyright_repo: CopyrightRepo
    ) -> None:
        copyright_repo.write("a.gen.go", copyright_repo.year + 1)
        copyright_repo.run("bash", "scripts/update_copyrights.sh", "a.gen.go")
        assert copyright_repo.year_of("a.gen.go") == copyright_repo.year
