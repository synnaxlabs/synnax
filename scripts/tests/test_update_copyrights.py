import pytest
from conftest import CopyrightRepo

ORACLE = "// Code generated by oracle. DO NOT EDIT.\n\npackage x\n"
STRINGER = '// Code generated by "stringer -type=Kind"; DO NOT EDIT.\n\npackage x\n'
TOOL = "// Code generated by gen.go. DO NOT EDIT.\n\npackage x\n"
TEMPLATE = 'var t = "// Code generated by oracle. DO NOT EDIT."\n'


class TestUpdateCopyrights:
    """Runs update_copyrights.sh on Oracle outputs and other files."""

    @pytest.mark.parametrize(
        ("name", "body"),
        [("a.pb.go", "package x\n"), ("a.gen.go", ORACLE), ("a_gen_test.go", ORACLE)],
    )
    def test_should_keep_a_past_year_in_an_oracle_output(
        self, copyright_repo: CopyrightRepo, name: str, body: str
    ) -> None:
        copyright_repo.write(name, copyright_repo.year - 3, body)
        before = (copyright_repo.path / name).read_text()
        result = copyright_repo.run("bash", "scripts/update_copyrights.sh", name)
        assert result.returncode == 0, result.stderr
        assert "Skipped 1 file" in result.stdout
        assert (copyright_repo.path / name).read_text() == before

    @pytest.mark.parametrize(
        ("name", "body"),
        [
            ("a.go", "package x\n"),
            ("a.go", TEMPLATE),
            ("kind_string.go", STRINGER),
            ("zoneinfo.gen.go", TOOL),
        ],
    )
    def test_should_set_the_current_year_in_any_other_file(
        self, copyright_repo: CopyrightRepo, name: str, body: str
    ) -> None:
        copyright_repo.write(name, copyright_repo.year - 3, body)
        result = copyright_repo.run("bash", "scripts/update_copyrights.sh", name)
        assert result.returncode == 0, result.stderr
        assert copyright_repo.year_of(name) == copyright_repo.year

    def test_should_set_the_current_year_for_a_future_year_in_an_oracle_output(
        self, copyright_repo: CopyrightRepo
    ) -> None:
        copyright_repo.write("a.gen.go", copyright_repo.year + 1, ORACLE)
        copyright_repo.run("bash", "scripts/update_copyrights.sh", "a.gen.go")
        assert copyright_repo.year_of("a.gen.go") == copyright_repo.year
