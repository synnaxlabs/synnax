from pathlib import Path

from check_docstrings_py import Finding, check

GOOGLE = '''def f(a: int) -> int:
    """Doubles a.

    Args:
        a: The number.

    Returns:
        Twice a.
    """
    return a * 2
'''

SPHINX = '''def f(a: int) -> int:
    """Doubles a.

    :param a: The number.
    :returns: Twice a.
    """
    return a * 2
'''


def write(root: Path, files: dict[str, str]) -> None:
    for name, source in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source)


class TestCheck:
    """Tests which docstring lines the check reports."""

    def test_should_report_each_google_section_header(self, tmp_path: Path) -> None:
        write(tmp_path, {"pkg/mod.py": GOOGLE})
        assert check(tmp_path) == [
            Finding(
                path="pkg/mod.py",
                line=4,
                message="use Sphinx fields, not a Google Args: section",
            ),
            Finding(
                path="pkg/mod.py",
                line=7,
                message="use Sphinx fields, not a Google Returns: section",
            ),
        ]

    def test_should_report_a_return_field(self, tmp_path: Path) -> None:
        write(tmp_path, {"mod.py": 'X = 1\n"""The limit.\n\n:return: One.\n"""\n'})
        assert check(tmp_path) == [
            Finding(path="mod.py", line=4, message="use :returns:, not :return:")
        ]

    def test_should_accept_sphinx_fields(self, tmp_path: Path) -> None:
        write(tmp_path, {"mod.py": SPHINX})
        assert check(tmp_path) == []

    def test_should_ignore_a_section_header_outside_a_docstring(
        self, tmp_path: Path
    ) -> None:
        write(tmp_path, {"mod.py": 'TEXT = """\nArgs:\n"""\n# Returns:\n'})
        assert check(tmp_path) == []

    def test_should_skip_generated_files(self, tmp_path: Path) -> None:
        write(
            tmp_path, {"mod.py": "# Code generated by Oracle. DO NOT EDIT.\n" + GOOGLE}
        )
        assert check(tmp_path) == []

    def test_should_skip_virtual_environments(self, tmp_path: Path) -> None:
        write(tmp_path, {".venv/lib/mod.py": GOOGLE})
        assert check(tmp_path) == []
