ORACLE_BANNER_RE='^(//|#) Code generated by [Oo]racle\. DO NOT EDIT\.$'

# Reports whether Oracle owns the header of a file: a .pb.go file, or a file with the
# Oracle banner in its first 30 lines. Oracle keeps the header year of these files, so
# they may keep a past one. Reads the file's lines from LINES.
is_oracle_output() {
    case "$1" in
        *.pb.go) return 0 ;;
    esac
    local i
    for ((i = 0; i < ${#LINES[@]} && i < 30; i++)); do
        [[ ${LINES[i]} =~ $ORACLE_BANNER_RE ]] && return 0
    done
    return 1
}
