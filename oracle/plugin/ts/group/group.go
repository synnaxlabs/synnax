// Package group generates the TypeScript table of the record types that can sit in a
// group, from the @group fields of the schemas. The table goes next to the group
// record.
package group

import (
	"bytes"
	"path/filepath"
	"text/template"

	"github.com/synnaxlabs/oracle/domain/group"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/domain"
	"github.com/synnaxlabs/oracle/plugin/enum"
	"github.com/synnaxlabs/oracle/plugin/output"
	"github.com/synnaxlabs/oracle/plugin/ts/internal/paths"
)

// Options configures the ts/group plugin.
type Options struct {
	// FileNamePattern is the basename written next to the group record.
	FileNamePattern string
}

// DefaultOptions returns the default plugin options.
func DefaultOptions() Options { return Options{FileNamePattern: "members.gen.ts"} }

// Plugin generates the TypeScript table of group members.
type Plugin struct {
	// Options sets the name of the generated file.
	Options Options
}

// New creates a new ts/group plugin with the given options.
func New(opts Options) *Plugin { return &Plugin{Options: opts} }

// Name returns the plugin identifier.
func (p *Plugin) Name() string { return "ts/group" }

// Domains returns the domains this plugin handles.
func (p *Plugin) Domains() []string { return []string{"ts"} }

// Requires returns plugin dependencies.
func (p *Plugin) Requires() []string { return []string{"ts/types"} }

// Generate emits one file next to the group record when any field carries @group.
func (p *Plugin) Generate(req *plugin.Request) (*plugin.Response, error) {
	resp := &plugin.Response{}
	data, err := group.Extract(req.Resolutions)
	if err != nil {
		return nil, err
	}
	if data == nil {
		return resp, nil
	}
	outputPath := output.GetPath(data.Record, "ts")
	if outputPath == "" {
		return resp, nil
	}
	td := templateData{Types: domain.GetName(data.Types, "ts")}
	typesPath := enum.FindOutputPath(data.Types, req.Resolutions, "ts")
	if typesPath != outputPath {
		td.Namespace = filepath.Base(typesPath)
		td.Import = paths.CalculateImport(outputPath, typesPath)
		td.Types = td.Namespace + "." + td.Types
	}
	for _, m := range data.Members {
		td.Members = append(td.Members, memberData{
			Type:   m.Type.StringValue(),
			Scope:  m.Scope.StringValue(),
			Pinned: m.Pinned,
		})
	}
	var buf bytes.Buffer
	if err := fileTemplate.Execute(&buf, td); err != nil {
		return nil, err
	}
	resp.Files = append(resp.Files, plugin.File{
		Path:    outputPath + "/" + p.Options.FileNamePattern,
		Content: buf.Bytes(),
	})
	return resp, nil
}

type templateData struct {
	// Namespace is the namespace that holds the resource types, or "" when the
	// generated file declares them.
	Namespace string
	// Import is the module that exports Namespace.
	Import string
	// Types is the TypeScript type of a resource type, such as resource.Type.
	Types string
	// Members are the record types that can sit in a group.
	Members []memberData
}

type memberData struct {
	// Type is the value of the record's resource type.
	Type string
	// Scope is the value of the scope of the groups that hold the record.
	Scope string
	// Pinned is true when the top parent of the group must be the record's holder.
	Pinned bool
}

var fileTemplate = template.Must(
	template.New("ts-group").Parse(`// Code generated by Oracle. DO NOT EDIT.
{{- if .Namespace}}

import { type {{.Namespace}} } from "{{.Import}}";
{{- end}}

/** Says which groups can hold a record of one type. */
export interface MemberRule {
  /** The scope of the groups that hold the type. */
  scope: {{.Types}};
  /**
   * True when the top parent of the group must be the record's holder, or none when
   * the record has no holder.
   */
  pinned: boolean;
}

/** The rule of each type that can sit in a group. */
export const MEMBER_RULES = {
{{- range .Members}}
  {{.Type}}: { scope: "{{.Scope}}", pinned: {{.Pinned}} },
{{- end}}
} as const satisfies Partial<Record<{{.Types}}, MemberRule>>;

/** A type that can sit in a group. */
export type MemberType = keyof typeof MEMBER_RULES;
`),
)
