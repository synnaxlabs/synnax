// Package actions emits a TypeScript discriminated-union action codec for any
// oracle struct that declares one or more actions. Each action becomes a zod
// payload schema, an Action union dispatches by literal type, and the plugin
// emits Handlers / HandlerResult / ReduceAllResult types together with
// createReducer / createReduceAll factories that bind a caller-provided
// Handlers object via immer's produce. Each handler returns a HandlerResult
// (inverse actions + touched targets) so the generated reduceAll can
// accumulate undo data alongside the next state. The per-action handler
// functions are hand-written and supplied by the caller; this plugin does not
// generate them.
package actions

import (
	"bytes"
	"text/template"

	"github.com/synnaxlabs/oracle/domain/doc"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/internal/casing"
	"github.com/synnaxlabs/oracle/plugin/output"
	"github.com/synnaxlabs/oracle/plugin/ts/internal/imports"
	"github.com/synnaxlabs/oracle/plugin/ts/internal/paths"
	tstypes "github.com/synnaxlabs/oracle/plugin/ts/types"
	"github.com/synnaxlabs/oracle/resolution"
)

// Options configures the actions plugin output.
type Options struct {
	// FileNamePattern is the basename written for each output package.
	FileNamePattern string
}

// DefaultOptions returns the production defaults: actions.gen.ts.
func DefaultOptions() Options {
	return Options{FileNamePattern: "actions.gen.ts"}
}

// Plugin emits the generated TS action codec.
type Plugin struct{ Options Options }

// New constructs a Plugin with the given options.
func New(opts Options) *Plugin { return &Plugin{Options: opts} }

func (p *Plugin) Name() string                  { return "ts/actions" }
func (p *Plugin) Domains() []string             { return []string{"ts"} }
func (p *Plugin) Requires() []string            { return []string{"ts/types"} }
func (p *Plugin) Check(_ *plugin.Request) error { return nil }

// Generate emits one actions.gen.ts per output package containing structs that
// declare actions. Structs without actions are skipped.
func (p *Plugin) Generate(req *plugin.Request) (*plugin.Response, error) {
	resp := &plugin.Response{Files: make([]plugin.File, 0)}
	for _, typ := range req.Resolutions.StructTypes() {
		form, ok := typ.Form.(resolution.StructForm)
		if !ok || len(form.Actions) == 0 {
			continue
		}
		outputPath := output.GetPath(typ, "ts")
		if outputPath == "" {
			continue
		}
		content, err := p.generateFile(typ, form, outputPath, req)
		if err != nil {
			return nil, err
		}
		resp.Files = append(resp.Files, plugin.File{
			Path:    outputPath + "/" + p.Options.FileNamePattern,
			Content: content,
		})
	}
	return resp, nil
}

func (p *Plugin) generateFile(
	typ resolution.Type,
	form resolution.StructForm,
	outputPath string,
	req *plugin.Request,
) ([]byte, error) {
	mgr := imports.NewManager()
	fp := &tstypes.FieldProcessor{
		Imports:    mgr,
		Namespace:  typ.Namespace,
		OutputPath: outputPath,
		Request:    req,
	}

	data := &templateData{
		Manager:        mgr,
		TargetType:     casing.TypeCamel(typ.Name),
		TargetTypeName: typ.Name,
	}

	for _, action := range form.Actions {
		a := actionData{
			Name:     casing.TypePascal(action.Name),
			TypeName: casing.TypeSnake(action.Name),
			Doc:      doc.Get(action.Domains),
		}
		for _, field := range action.Fields {
			a.Fields = append(a.Fields, fp.ProcessField(field, typ))
			fp.CollectTypeImports(&field.Type)
		}
		data.Actions = append(data.Actions, a)
	}

	mgr.AddImport("zod", "z")
	mgr.AddImport("immer", "Draft")
	mgr.AddImport("immer", "produce")
	sameDir := paths.CalculateImport(outputPath, outputPath)
	mgr.AddImport(sameDir+"/types.gen", typ.Name)

	var buf bytes.Buffer
	if err := fileTemplate.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

type templateData struct {
	*imports.Manager
	TargetType     string
	TargetTypeName string
	Actions        []actionData
}

type actionData struct {
	Name     string
	TypeName string
	Doc      string
	Fields   []tstypes.FieldData
}

var templateFuncs = template.FuncMap{
	"camelCase":  casing.TypeCamel,
	"pascalCase": casing.TypePascal,
	"formatDoc":  doc.FormatTS,
}

var fileTemplate = template.Must(template.New("ts-actions").Funcs(templateFuncs).Parse(`// Code generated by Oracle. DO NOT EDIT.
{{- range .SynnaxImports }}
import { {{ range $i, $name := .Names }}{{ if $i }}, {{ end }}{{ $name }}{{ end }} } from "{{ .Path }}";
{{- end }}
{{- range .ExternalNamedImports }}
import { {{ range $i, $name := .Names }}{{ if $i }}, {{ end }}{{ $name }}{{ end }} } from "{{ .Path }}";
{{- end }}
{{- range .InternalNamedImports }}
import { {{ range $i, $name := .Names }}{{ if $i }}, {{ end }}{{ $name }}{{ end }} } from "{{ .Path }}";
{{- end }}
{{range .Actions}}
{{- if .Doc}}
{{formatDoc .Name .Doc}}
{{- end}}
export const {{ camelCase .Name }}PayloadZ = z.object({
{{- range .Fields}}
  {{ .TSName }}: {{ .ZodType }},
{{- end}}
});

export type {{ .Name }}Payload = z.infer<typeof {{ camelCase .Name }}PayloadZ>;
{{end}}
export const actionZ = z.discriminatedUnion("type", [
{{- range .Actions}}
  z.object({ type: z.literal("{{ .TypeName }}"), {{ camelCase .Name }}: {{ camelCase .Name }}PayloadZ }),
{{- end}}
]);

export type Action = z.infer<typeof actionZ>;
{{range .Actions}}
export const {{ camelCase .Name }} = (payload: {{ .Name }}Payload): Action => ({
  type: "{{ .TypeName }}",
  {{ camelCase .Name }}: payload,
});
{{end}}
export interface HandlerResult {
  inverse: Action[];
  /** Document keys this handler touched (or considered touching). */
  targets: readonly string[];
}

export interface Handlers {
{{- range .Actions}}
  {{ camelCase .Name }}: (state: Draft<{{ $.TargetTypeName }}>, payload: {{ .Name }}Payload) => HandlerResult;
{{- end}}
}

export interface ReduceAllResult {
  next: {{ .TargetTypeName }};
  inverse: Action[];
  targets: readonly string[];
}

export const createReduceAll = (handlers: Handlers) => {
  const reduce = (state: Draft<{{ .TargetTypeName }}>, action: Action): HandlerResult => {
    switch (action.type) {
{{- range .Actions}}
      case "{{ .TypeName }}":
        return handlers.{{ camelCase .Name }}(state, action.{{ camelCase .Name }});
{{- end}}
    }
  };
  return (state: {{ .TargetTypeName }}, actions: Action[]): ReduceAllResult => {
    const inverse: Action[] = [];
    const targetsSet = new Set<string>();
    const next = produce(state, (draft) => {
      for (const action of actions) {
        const result = reduce(draft, action);
        if (result.inverse.length > 0) inverse.unshift(...result.inverse);
        for (const t of result.targets) targetsSet.add(t);
      }
    });
    return { next, inverse, targets: Array.from(targetsSet) };
  };
};
`))
