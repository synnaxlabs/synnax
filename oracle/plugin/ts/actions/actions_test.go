package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/ts/actions"
	. "github.com/synnaxlabs/oracle/testutil"
)

func TestTSActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "TS Actions Plugin Suite")
}

var _ = Describe("TS Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("ts/actions"))
		})

		It("Should filter on ts domain", func() {
			Expect(p.Domains()).To(Equal([]string{"ts"}))
		})

		It("Should require ts/types", func() {
			Expect(p.Requires()).To(Equal([]string{"ts/types"}))
		})

		It("Should have a no-op Check", func() {
			Expect(p.Check(nil)).To(Succeed())
		})
	})

	Describe("Generate", func() {
		Context("structs without actions", func() {
			It("Should not emit an actions.gen.ts file", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/user"

					User struct {
						key  uuid
						name string
					}
				`
				resp := MustGenerate(ctx, source, "user", loader, p)
				for _, f := range resp.Files {
					Expect(f.Path).ToNot(HaveSuffix("actions.gen.ts"))
				}
			})
		})

		Context("structs with actions", func() {
			It("Should emit a discriminated-union codec with a Handlers interface and createReducer/createReduceAll factories", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key   uuid
						value int32

						action SetValue {
							value int32
						}

						action Increment {
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				content := ExpectContent(resp, "actions.gen.ts")
				content.ToContain(
					"// Code generated by Oracle. DO NOT EDIT.",
					"export const setValuePayloadZ = z.object({",
					"export type SetValuePayload",
					"export const incrementPayloadZ = z.object({",
					"export type IncrementPayload",
					"export const actionZ = z.discriminatedUnion(\"type\", [",
					"z.literal(\"set_value\")",
					"z.literal(\"increment\")",
					"export type Action",
					"export const setValue = (payload: SetValuePayload): Action",
					"export const increment = (payload: IncrementPayload): Action",
					"export interface Handlers {",
					"setValue: (state: Counter, payload: SetValuePayload) => void;",
					"increment: (state: Counter, payload: IncrementPayload) => void;",
					"export const createReducer =",
					"(handlers: Handlers) =>",
					"(state: Counter, action: Action): Counter =>",
					"case \"set_value\":",
					"handlers.setValue(state, action.setValue);",
					"case \"increment\":",
					"handlers.increment(state, action.increment);",
					"export const createReduceAll = (handlers: Handlers) =>",
					"const reduce = createReducer(handlers);",
					"(state: Counter, actions: Action[]): Counter =>",
					"produce(state, (draft) => actions.forEach((action) => reduce(draft, action)))",
				)
				content.ToNotContain("ACTION_TYPES")
			})

			It("Should snake_case action types and camelCase handler/constructor names", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Board struct {
						key uuid

						action SetNodePosition {
							key string
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"export const setNodePosition",
						"setNodePosition: (state: Board, payload: SetNodePositionPayload) => void;",
						"handlers.setNodePosition(state, action.setNodePosition);",
						"z.literal(\"set_node_position\")",
					)
			})

			It("Should not import handler functions from any sibling module", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/widget"

					Widget struct {
						key uuid

						action Toggle {
						}
					}
				`
				resp := MustGenerate(ctx, source, "widget", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToNotContain(
						"handleToggle",
						`from "@/widget/actions"`,
					)
			})

			It("Should import the target type from the sibling types.gen module", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/widget"

					Widget struct {
						key uuid

						action Toggle {
						}
					}
				`
				resp := MustGenerate(ctx, source, "widget", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"Widget",
						`from "@/widget/types.gen"`,
					)
			})

			It("Should add zod imports for action field types in the same namespace", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Tile struct {
						key   string
						value int32
					}

					Board struct {
						key uuid

						action AddTile {
							tile Tile
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain("tileZ", `from "@/board/types.gen"`)
			})

			It("Should recurse through type args when collecting same-namespace zod imports", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Tile struct {
						key   string
						value int32
					}

					Board struct {
						key uuid

						action AddTiles {
							tiles Tile[]
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain("tileZ", `from "@/board/types.gen"`)
			})
		})
	})
})
