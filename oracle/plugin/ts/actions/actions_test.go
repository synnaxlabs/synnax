package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/ts/actions"
	. "github.com/synnaxlabs/oracle/testutil"
	. "github.com/synnaxlabs/x/testutil"
)

func TestTSActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin TS Actions Suite")
}

var _ = Describe("TS Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("ts/actions"))
		})

		It("Should filter on ts domain", func() {
			Expect(p.Domains()).To(Equal([]string{"ts"}))
		})

		It("Should require ts/types", func() {
			Expect(p.Requires()).To(Equal([]string{"ts/types"}))
		})

		It("Should have a no-op Check", func() {
			Expect(p.Check(nil)).To(Succeed())
		})
	})

	Describe("Generate", func() {
		Context("structs without actions", func() {
			It("Should not emit an actions.gen.ts file", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/user"

					User struct {
						key  uuid
						name string
					}
				`
				resp := MustGenerate(ctx, source, "user", loader, p)
				for _, f := range resp.Files {
					Expect(f.Path).ToNot(HaveSuffix("actions.gen.ts"))
				}
			})
		})

		Context("structs with actions", func() {
			It("Should emit a discriminated-union codec with HandlerResult/ReduceAllResult aliases and a createReduceAll wrapper delegating to @/actions", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key   uuid
						value int32

						action SetValue {
							value int32
						}

						action Increment {
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"// Code generated by Oracle. DO NOT EDIT.",
						`import { actions } from "@/actions";`,
						"export const setValuePayloadZ = z.object({",
						"export type SetValuePayload",
						"export const incrementPayloadZ = z.object({",
						"export type IncrementPayload",
						"export const actionZ = z.discriminatedUnion(\"type\", [",
						"z.literal(\"set_value\")",
						"z.literal(\"increment\")",
						"export type Action",
						"export const setValue = (payload: z.input<typeof setValuePayloadZ>): Action",
						"export const increment = (payload: z.input<typeof incrementPayloadZ>): Action",
						"setValue: setValuePayloadZ.parse(payload),",
						"increment: incrementPayloadZ.parse(payload),",
						"export type HandlerResult = actions.HandlerResult<Action>;",
						"export type ReduceAllResult = actions.ReduceAllResult<Counter, Action>;",
						"export interface Handlers {",
						"setValue: (state: Draft<Counter>, payload: SetValuePayload) => HandlerResult;",
						"increment: (state: Draft<Counter>, payload: IncrementPayload) => HandlerResult;",
						"export const createReduceAll = (handlers: Handlers) =>",
						"actions.createReduceAll<Counter, Action>((state, action) =>",
						"case \"set_value\":",
						"return handlers.setValue(state, action.setValue);",
						"case \"increment\":",
						"return handlers.increment(state, action.increment);",
					)
			})

			It("Should flatten fields from an extended struct into the action payload", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Named struct {
						name string
					}

					Counter struct {
						key uuid

						action Rename extends Named {
							force int32
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"export const renamePayloadZ = z.object({",
						"name: z.string()",
						"force: z.int32()",
					)
			})

			It("Should emit scopedActionZ and dispatchReqZ bound to keyZ and actionZ", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key uuid

						action Tick {
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						`import { Counter, keyZ } from "@/counter/types.gen";`,
						"export const scopedActionZ = actions.scopedZ(keyZ, actionZ);",
						"export const dispatchReqZ = actions.dispatchReqZ(keyZ, actionZ);",
					)
			})

			It("Should not emit the inlined HandlerResult/ReduceAllResult interfaces or open-coded produce loop", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key uuid

						action Tick {
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToNotContain(
						"export interface HandlerResult {",
						"export interface ReduceAllResult {",
						"produce",
						"targetsSet",
					)
			})

			It("Should not emit a single-action createReducer factory", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key   uuid

						action Tick {
						}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToNotContain("export const createReducer")
			})

			It("Should snake_case action types and camelCase handler/constructor names", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Board struct {
						key uuid

						action SetNodePosition {
							key string
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"export const setNodePosition",
						"setNodePosition: (state: Draft<Board>, payload: SetNodePositionPayload) => HandlerResult;",
						"return handlers.setNodePosition(state, action.setNodePosition);",
						"z.literal(\"set_node_position\")",
					)
			})

			It("Should not import handler functions from any sibling module", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/widget"

					Widget struct {
						key uuid

						action Toggle {
						}
					}
				`
				resp := MustGenerate(ctx, source, "widget", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToNotContain(
						"handleToggle",
						`from "@/widget/actions"`,
					)
			})

			It("Should import the target type from the sibling types.gen module", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/widget"

					Widget struct {
						key uuid

						action Toggle {
						}
					}
				`
				resp := MustGenerate(ctx, source, "widget", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain(
						"Widget",
						`from "@/widget/types.gen"`,
					)
			})

			It("Should add zod imports for action field types in the same namespace", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Tile struct {
						key   string
						value int32
					}

					Board struct {
						key uuid

						action AddTile {
							tile Tile
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain("tileZ", `from "@/board/types.gen"`)
			})

			It("Should recurse through type args when collecting same-namespace zod imports", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/board"

					Tile struct {
						key   string
						value int32
					}

					Board struct {
						key uuid

						action AddTiles {
							tiles Tile[]
						}
					}
				`
				resp := MustGenerate(ctx, source, "board", loader, p)
				ExpectContent(resp, "actions.gen.ts").
					ToContain("tileZ", `from "@/board/types.gen"`)
			})
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
