package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/ts/actions"
	. "github.com/synnaxlabs/oracle/testutil"
	. "github.com/synnaxlabs/x/testutil"
)

func TestTSActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin TS Actions Suite", SuiteConfig())
}

var _ = Describe("TS Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("ts/actions"))
		})

		It("Should filter on ts domain", func() {
			Expect(p.Domains()).To(Equal([]string{"ts"}))
		})

		It("Should require ts/types", func() {
			Expect(p.Requires()).To(Equal([]string{"ts/types"}))
		})
	})

	Describe("Generate", func() {
		Context("structs without actions", func() {
			It("Should not emit an actions.gen.ts file", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/user"

					User struct {
						key  uuid
						name string
					}
				`
				resp := MustGenerate(ctx, source, "user", loader, p)
				for _, f := range resp.Files {
					Expect(f.Path).ToNot(HaveSuffix("actions.gen.ts"))
				}
			})
		})

		Context("hand-written types", func() {
			It("Should not emit an actions.gen.ts file", func(ctx SpecContext) {
				source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key uuid

						action Reset {
						}

						@ts hand
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				for _, f := range resp.Files {
					Expect(f.Path).ToNot(HaveSuffix("actions.gen.ts"))
				}
			})
		})

		Context("unions with actions", func() {
			It("Should emit actions whose handlers take the union", func(
				ctx SpecContext,
			) {
				source := `
					@ts output "client/ts/src/shape"

					Base struct {
						key  uuid @key
						name string
					}

					Shape union on type extends Base {
						circle {
							radius float64
						}
						square {}

						action Rename {
							name string
						}
					}
				`
				resp := MustGenerate(ctx, source, "shape", loader, p)
				ExpectContent(resp, "actions.gen.ts").ToContain(
					"rename: (state: Draft<Shape>, payload: RenamePayload) => HandlerResult;",
					"actions.createReduceAll<Shape, Action>((state, action) =>",
				)
			})
		})

		Context("structs with actions", func() {
			It(
				"Should emit a builder per action, the Handlers, and createReduceAll",
				func(ctx SpecContext) {
					source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key   uuid @key
						value int32

						action SetValue {
							value int32
						}

						action Increment {}
					}
				`
					resp := MustGenerate(ctx, source, "counter", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"// Code generated by Oracle. DO NOT EDIT.",
							`import { actions } from "@/actions";`,
							`from "@/counter/types.gen";`,
							"export const setValue = (payload: z.input<typeof setValuePayloadZ>): Action => ({",
							`type: "set_value",`,
							`setValue: zod.parse(setValuePayloadZ, payload, { label: "counter.SetValuePayload" }),`,
							"export const increment = (payload: z.input<typeof incrementPayloadZ>): Action => ({",
							"export type HandlerResult = actions.HandlerResult<Action>;",
							"export type ReduceAllResult = actions.ReduceAllResult<Counter, Action>;",
							"export interface Handlers {",
							"setValue: (state: Draft<Counter>, payload: SetValuePayload) => HandlerResult;",
							"increment: (state: Draft<Counter>, payload: IncrementPayload) => HandlerResult;",
							"export const createReduceAll = (handlers: Handlers) =>",
							`case "set_value":`,
							"return handlers.setValue(state, action.setValue);",
							"export const scopedActionZ = actions.scopedZ(z.uuid(), actionZ);",
							"export const dispatchReqZ = actions.dispatchReqZ(z.uuid(), actionZ);",
							"export const dispatchResZ = actions.dispatchResZ(actionZ);",
						).
						ToNotContain(
							"export const setValuePayloadZ",
							"export type Action =",
							"export const createReducer",
						)
				},
			)

			It(
				"Should emit no builder for the action that only the Core emits",
				func(ctx SpecContext) {
					loader.Add("schemas/x/patch", `
						@ts output "x/ts/src/patch"

						Set struct { path string[] }
						Remove struct { path string[] }
						Insert struct { path string[] }
						Move struct { path string[] }
					`)
					source := `
					import "schemas/x/patch"

					@ts output "client/ts/src/board"

					Board struct {
						key uuid @key

						@actions
					}
				`
					resp := MustGenerate(ctx, source, "board", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"export const set = (payload: z.input<typeof setPayloadZ>): Action",
							"create: (state: Draft<Board>, payload: CreatePayload) => HandlerResult;",
							`case "create":`,
							"const dispatchedActionZ: z.ZodType<SetAction | RemoveAction | "+
								"InsertAction | MoveAction> =\n"+
								`  z.discriminatedUnion("type", [setActionZ, removeActionZ, `+
								"insertActionZ, moveActionZ]);",
							"export const dispatchReqZ = actions.dispatchReqZ(z.uuid(), "+
								"dispatchedActionZ);",
							"export const scopedActionZ = actions.scopedZ(z.uuid(), actionZ);",
						).
						ToNotContain("export const create =", "createPayloadZ")
				},
			)

			It(
				"Should apply the update in the reducer instead of a handler",
				func(ctx SpecContext) {
					loader.Add("schemas/x/patch", `
						@ts output "x/ts/src/patch"

						Set struct { path string[] }
						Remove struct { path string[] }
						Insert struct { path string[] }
						Move struct { path string[] }
						Change struct<T> {
							value T?
							@presence
						}
						Update struct<V> { value V }
					`)
					source := `
					import "schemas/x/patch"

					@ts output "client/ts/src/board"

					Board struct {
						key  uuid @key
						name string { @patch }

						@actions
					}
				`
					resp := MustGenerate(ctx, source, "board", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"export const update = "+
								"(payload: z.input<typeof updatePayloadZ>)",
							"const updateSchemas = { u: updateZ, t: boardZ };",
							`case "update":`+"\n"+
								"        return actions.applyUpdate("+
								"state, action.update, updateSchemas);",
						).
						ToNotContain("update: (state: Draft<Board>")
				},
			)

			It(
				"Should name the state type by its TS name",
				func(ctx SpecContext) {
					source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						key uuid @key

						action Reset {}

						@ts name "Payload"
					}
				`
					resp := MustGenerate(ctx, source, "counter", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"export type ReduceAllResult = actions.ReduceAllResult<Payload, Action>;",
							"reset: (state: Draft<Payload>, payload: ResetPayload) => HandlerResult;",
						).
						ToNotContain("Draft<Counter>")
				},
			)

			It(
				"Should bind scopedActionZ and dispatchReqZ to a retrieve key override",
				func(ctx SpecContext) {
					source := `
					@ts output "client/ts/src/counter"

					Counter struct {
						name string

						action Tick {}

						@retrieve key "string"
					}
				`
					resp := MustGenerate(ctx, source, "counter", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"export const scopedActionZ = actions.scopedZ(z.string(), actionZ);",
							"export const dispatchReqZ = actions.dispatchReqZ(z.string(), actionZ);",
						)
				},
			)

			It("Should require a key", func(ctx SpecContext) {
				req := MustGenerateRequest(ctx, `
					@ts output "client/ts/src/counter"

					Counter struct {
						name string

						action Tick {}
					}
				`, "counter", loader)
				Expect(p.Generate(req)).Error().
					To(MatchError("counter.Counter: actions need a @key field"))
			})

			It(
				"Should camelCase the builder and handler of a multi-word action",
				func(ctx SpecContext) {
					source := `
					@ts output "client/ts/src/board"

					Board struct {
						key uuid @key

						action SetNodePosition {
							key string
						}
					}
				`
					resp := MustGenerate(ctx, source, "board", loader, p)
					ExpectContent(resp, "actions.gen.ts").
						ToContain(
							"export const setNodePosition",
							`type: "set_node_position",`,
							"return handlers.setNodePosition(state, action.setNodePosition);",
						)
				},
			)
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
