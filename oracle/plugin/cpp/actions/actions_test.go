package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/cpp/actions"
	. "github.com/synnaxlabs/oracle/testutil"
	. "github.com/synnaxlabs/x/testutil"
)

func TestCppActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin C++ Actions Suite", SuiteConfig())
}

var _ = Describe("C++ Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("cpp/actions"))
		})

		It("Should filter on cpp domain", func() {
			Expect(p.Domains()).To(Equal([]string{"cpp"}))
		})

		It("Should require cpp/json", func() {
			Expect(p.Requires()).To(Equal([]string{"cpp/json"}))
		})
	})

	Describe("Generate", func() {
		DescribeTable("Should not emit an actions.gen.h file",
			func(ctx SpecContext, source string) {
				resp := MustGenerate(ctx, source, "counter", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
			Entry("for a struct without actions", `
				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid
				}
			`),
			Entry("for a hand-written struct", `
				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid

					action Reset {}

					@cpp hand
				}
			`),
			Entry("for a struct that C++ omits", `
				@cpp output "client/cpp/counter"
				@go output "core/pkg/service/counter"

				Tally struct {
					count int32
				}

				Counter struct {
					key uuid

					action Reset {}

					@cpp omit
				}
			`),
			Entry("for a struct with no C++ output", `
				@go output "core/pkg/service/counter"

				Counter struct {
					key uuid

					action Reset {}
				}
			`),
		)

		It("Should emit payload structs with a codec and a type", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@cpp output "client/cpp/counter"

				Counter struct {
					key   uuid
					value int32

					action SetValue {
						value int32   { @doc value "is the new value." }
						note  string?

						@doc value "sets the value of the counter."
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "client/cpp/counter/actions.gen.h").ToNotContain(
				"TYPE",
			).ToContain(
				"// Code generated by oracle. DO NOT EDIT.",
				`#include "client/cpp/counter/json.gen.h"`,
				"namespace synnax::counter {",
				"/// @brief SetValuePayload sets the value of the counter.\n"+
					"struct SetValuePayload {",
				"/// @brief value is the new value.",
				"std::int32_t value = 0;",
				"std::optional<std::string> note;",
				"static SetValuePayload parse(x::json::Parser parser);",
				"[[nodiscard]] x::json::json to_json() const;",
				"inline SetValuePayload SetValuePayload::parse("+
					"x::json::Parser parser) {",
				`.value = parser.field<std::int32_t>("value"),`,
				`.note = parser.field<std::optional<std::string>>("note"),`,
				"inline x::json::json SetValuePayload::to_json() const {",
				`j["value"] = this->value;`,
				`if (this->note.has_value()) j["note"] = *this->note;`,
			)
		})

		It("Should emit an Action variant with a JSON envelope codec", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid

					action SetValue {
						value int32
					}

					action Reset {}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions.gen.h").ToContain(
				"/// @brief Action is a discriminated union for all Counter mutations.",
				"using Action = std::variant<SetValuePayload, ResetPayload>;",
				"Action parse_action(x::json::Parser parser);",
				"[[nodiscard]] x::json::json to_json(const Action &value);",
				"inline Action parse_action(x::json::Parser parser) {",
				`const auto type = parser.field<std::string>("type");`,
				`if (type == "set_value") return SetValuePayload::parse(`+
					`parser.child("set_value"));`,
				`if (type == "reset") return ResetPayload::parse(parser.child("reset"));`,
				`parser.field_err("type", "unknown Action type: " + type);`,
				"inline x::json::json to_json(const Action &value) {",
				`if constexpr (std::is_same_v<Payload, SetValuePayload>) `+
					`type = "set_value";`,
				`else if constexpr (std::is_same_v<Payload, ResetPayload>) `+
					`type = "reset";`,
				`j["type"] = type;`,
				"j[type] = payload.to_json();",
				"inline ResetPayload ResetPayload::parse(x::json::Parser) {",
			)
		})

		It("Should emit a builder per action", func(ctx SpecContext) {
			resp := MustGenerate(ctx, `
				@cpp output "client/cpp/board"

				Board struct {
					key uuid

					action SetNodePosition {
						key string
					}

					action Delete {}
				}
			`, "board", loader, p)
			ExpectContent(resp, "actions.gen.h").ToContain(
				"inline Action set_node_position(SetNodePositionPayload payload) {",
				"inline Action delete_(DeletePayload payload) {",
				`if (type == "delete") return DeletePayload::parse(`+
					`parser.child("delete"));`,
			)
		})

		It("Should flatten fields from an extended struct into the payload", func(
			ctx SpecContext,
		) {
			loader.Add("schemas/patch", `
				@cpp output "x/cpp/patch"

				Guard struct {
					value string
				}

				Set struct {
					path   string[]
					value  any
					guards Guard[] = []
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid

					action Set extends patch.Set {}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions.gen.h").ToContain(
				`#include "x/cpp/patch/json.gen.h"`,
				"std::vector<std::string> path;",
				"x::json::json value;",
				"std::vector<::x::patch::Guard> guards = {};",
				`j["guards"] = x::json::to_array(this->guards);`,
				"inline Action set(SetPayload payload) {",
			)
		})

		It("Should alias the struct of an action alias", func(ctx SpecContext) {
			loader.Add("schemas/patch", `
				@cpp output "x/cpp/patch"

				Set struct {
					path string[]

					@doc value "replaces the value at a path."
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid

					action Set = patch.Set
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions.gen.h").ToNotContain(
				"struct SetPayload",
				"SetPayload::parse(x::json::Parser parser) {",
			).ToContain(
				`#include "x/cpp/patch/json.gen.h"`,
				"/// @brief SetPayload replaces the value at a path.\n"+
					"using SetPayload = ::x::patch::Set;",
				"using Action = std::variant<SetPayload>;",
				`if (type == "set") return SetPayload::parse(parser.child("set"));`,
				`if constexpr (std::is_same_v<Payload, SetPayload>) type = "set";`,
				"inline Action set(SetPayload payload) {",
			)
		})

		It("Should write the own doc of an action alias", func(ctx SpecContext) {
			loader.Add("schemas/patch", `
				@cpp output "x/cpp/patch"

				Set struct {
					path string[]

					@doc value "replaces the value at a path."
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@cpp output "client/cpp/counter"

				Counter struct {
					key uuid

					action Set = patch.Set {
						@doc value "replaces the value at a path in the counter."
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions.gen.h").ToContain(
				"/// @brief SetPayload replaces the value at a path in the counter.\n" +
					"using SetPayload = ::x::patch::Set;",
			).ToNotContain("/// @brief SetPayload replaces the value at a path.\n")
		})

		It("Should leave an omitted field out of a payload", func(ctx SpecContext) {
			resp := MustGenerate(ctx, `
				@cpp output "client/cpp/counter"
				@go output "core/pkg/service/counter"

				Counter struct {
					key uuid

					action SetValue {
						value  int32
						secret bytes { @cpp omit }
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions.gen.h").
				ToContain("std::int32_t value = 0;").
				ToNotContain("secret")
		})

		It("Should emit actions for a union and name its codec by namespace", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@cpp output "client/cpp/shape"

				Shape union on type {
					circle {
						radius float64
					}
					square {}

					action Create {
						shape Shape
					}
				}
			`, "shape", loader, p)
			ExpectContent(resp, "actions.gen.h").ToContain(
				"/// @brief Action is a discriminated union for all Shape mutations.",
				"Shape shape;",
				`.shape = parse_shape(parser.child("shape")),`,
				`j["shape"] = ::synnax::shape::to_json(this->shape);`,
			)
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
