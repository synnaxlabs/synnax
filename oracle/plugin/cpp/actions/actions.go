// Package actions emits a C++ header of action builders for each struct or union that
// has actions. The cpp/types and cpp/json plugins emit the payload structs, the Action
// std::variant, and its JSON codec. This plugin emits one builder per action that
// clients dispatch.
package actions

import (
	"bytes"
	"text/template"

	"github.com/synnaxlabs/oracle/internal/casing"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/cpp/internal/includes"
	cppjson "github.com/synnaxlabs/oracle/plugin/cpp/json"
	"github.com/synnaxlabs/oracle/plugin/cpp/keywords"
	cppnaming "github.com/synnaxlabs/oracle/plugin/cpp/naming"
	"github.com/synnaxlabs/oracle/plugin/domain"
	"github.com/synnaxlabs/oracle/plugin/output"
	"github.com/synnaxlabs/x/errors"
)

// Options configures the actions plugin output.
type Options struct {
	// FileNamePattern is the basename written for each output package.
	FileNamePattern string
}

// DefaultOptions returns the production defaults: actions.gen.h.
func DefaultOptions() Options {
	return Options{FileNamePattern: "actions.gen.h"}
}

// Plugin emits the generated C++ action builders.
type Plugin struct{ opts Options }

// New constructs a Plugin with the given options.
func New(opts Options) *Plugin { return &Plugin{opts: opts} }

func (*Plugin) Name() string       { return "cpp/actions" }
func (*Plugin) Domains() []string  { return []string{"cpp"} }
func (*Plugin) Requires() []string { return []string{"cpp/json"} }

// Generate emits one actions.gen.h per output package that holds a struct or union
// with actions that clients dispatch.
func (p *Plugin) Generate(req *plugin.Request) (*plugin.Response, error) {
	jsonPaths, err := cppjson.ContentPaths(req)
	if err != nil {
		return nil, err
	}
	resp := &plugin.Response{Files: make([]plugin.File, 0)}
	for _, typ := range domain.ActionTargets(req.Resolutions, "cpp") {
		outputPath := output.GetPath(typ, "cpp")
		mgr := includes.NewManager()
		mgr.AddInternal(cppjson.IncludeFor(jsonPaths, outputPath))
		data := &templateData{Manager: mgr, Namespace: cppnaming.Namespace(outputPath)}
		for _, action := range typ.Actions() {
			if action.CoreOnly {
				continue
			}
			payload, ok := action.Payload.Resolve(req.Resolutions)
			if !ok {
				return nil, errors.Newf(
					"%s: unresolved payload %s",
					typ.QualifiedName,
					action.Payload.Name,
				)
			}
			data.Builders = append(data.Builders, builderData{
				Name:    keywords.Escape(casing.TypeSnake(action.Name)),
				Payload: domain.GetName(payload, "cpp"),
			})
		}
		if len(data.Builders) == 0 {
			continue
		}
		var buf bytes.Buffer
		if err := fileTemplate.Execute(&buf, data); err != nil {
			return nil, err
		}
		resp.Files = append(resp.Files, plugin.File{
			Path:    outputPath + "/" + p.opts.FileNamePattern,
			Content: buf.Bytes(),
		})
	}
	return resp, nil
}

// templateData's fields are read by fileTemplate, so they must stay exported.
type templateData struct {
	*includes.Manager
	Namespace string
	Builders  []builderData
}

type builderData struct {
	Name    string
	Payload string
}

var fileTemplate = template.Must(
	template.New("cpp-actions").
		Parse(`// Code generated by oracle. DO NOT EDIT.

#pragma once

{{range .InternalIncludes -}}
#include "{{.}}"
{{end}}
namespace {{.Namespace}} {
{{- range .Builders}}

/// @brief returns an Action that carries the given payload.
inline Action {{.Name}}({{.Payload}} payload) {
    return payload;
}
{{- end}}

}
`),
)
