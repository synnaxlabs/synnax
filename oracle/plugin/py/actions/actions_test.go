func TestPyActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin Python Actions Suite", SuiteConfig())
}

var _ = Describe("Python Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("py/actions"))
		})

		It("Should filter on py domain", func() {
			Expect(p.Domains()).To(Equal([]string{"py"}))
		})

		It("Should require py/types", func() {
			Expect(p.Requires()).To(Equal([]string{"py/types"}))
		})
	})

	Describe("Generate", func() {
		DescribeTable("Should not emit an actions_gen.py file",
			func(ctx SpecContext, source string) {
				resp := MustGenerate(ctx, source, "counter", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
			Entry("for a struct without actions", `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid
				}
			`),
			Entry("for a hand-written struct", `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Reset {}

					@py hand
				}
			`),
			Entry("for a struct with no Python output", `
				@go output "core/pkg/service/counter"

				Counter struct {
					key uuid

					action Reset {}
				}
			`),
		)

		It("Should emit a payload model and an envelope per action", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"

				Counter struct {
					key   uuid
					value int32

					action SetValue {
						value int32   { @doc value "is the new value." }
						note  string?

						@doc value "sets the value of the counter."
					}

					action Reset {}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "client/py/synnax/counter/actions_gen.py").ToContain(
				"# Code generated by Oracle. DO NOT EDIT.",
				"class SetValuePayload(BaseModel):",
				`"""Sets the value of the counter.`,
				"value: Is the new value.",
				"value: int = Field(ge=-2147483648, le=2147483647)",
				"note: str | None = None",
				"class ResetPayload(BaseModel):\n    pass",
				"class SetValueAction(BaseModel):",
				`type: Literal["set_value"] = "set_value"`,
				"set_value: SetValuePayload",
				"class ResetAction(BaseModel):",
				"# Action is a discriminated union for all Counter mutations.",
				"Action = Annotated[\n    SetValueAction | ResetAction,\n"+
					`    Field(discriminator="type"),`,
				"def set_value(payload: SetValuePayload) -> SetValueAction:\n"+
					"    return SetValueAction(set_value=payload)",
				"def reset(payload: ResetPayload) -> ResetAction:",
			)
		})

		It("Should import a type of the namespace from the types module", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Create {
						counter Counter
					}

					@py name "Payload"
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"from synnax.counter.types_gen import Payload",
				"counter: Payload",
			)
		})

		It("Should import a type of another namespace through its module", func(
			ctx SpecContext,
		) {
			loader.Add("schemas/patch", `
				@py output "x/py/x/patch"

				Guard struct {
					value string
				}

				Set struct {
					path   string[]
					value  any
					guards Guard[] = []
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Set extends patch.Set {}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"from x import patch",
				"path: list[str] = Field(default_factory=list)",
				"value: JsonValue\n",
				"guards: list[patch.Guard] = Field(default_factory=list)",
				"def set(payload: SetPayload) -> SetAction:",
			)
		})

		It("Should alias the model of an action alias", func(ctx SpecContext) {
			loader.Add("schemas/patch", `
				@py output "x/py/x/patch"

				Set struct {
					path string[]

					@doc value "replaces the value at a path."
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Set = patch.Set
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"from x import patch",
				"\n# Replaces the value at a path.\nSetPayload = patch.Set\n",
				"set: SetPayload",
				"def set(payload: SetPayload) -> SetAction:",
			).ToNotContain("class SetPayload")
		})

		It("Should write the own doc of an action alias", func(ctx SpecContext) {
			loader.Add("schemas/patch", `
				@py output "x/py/x/patch"

				Set struct {
					path string[]

					@doc value "replaces the value at a path."
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/patch"

				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Set = patch.Set {
						@doc value "replaces the value at a path in the counter."
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"\n# Replaces the value at a path in the counter.\n" +
					"SetPayload = patch.Set\n",
			).ToNotContain("# Replaces the value at a path.\n")
		})

		It("Should alias a module import that a payload field shadows", func(
			ctx SpecContext,
		) {
			loader.Add("schemas/color", `
				@py output "x/py/x/color"

				Color struct {
					hex string
				}
			`)
			resp := MustGenerate(ctx, `
				import "schemas/color"

				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action SetColor {
						color color.Color
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"from x import color as color_",
				"color: color_.Color",
			)
		})

		It("Should give a keyword action an aliased envelope field", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Import {
						from string
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"model_config = ConfigDict(populate_by_name=True)",
				`from_: str = Field(alias="from")`,
				`import_: ImportPayload = Field(alias="import")`,
				`type: Literal["import"] = "import"`,
				"def import_(payload: ImportPayload) -> ImportAction:",
			)
		})

		It("Should leave an omitted field out of a payload", func(ctx SpecContext) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"
				@go output "core/pkg/service/counter"

				Counter struct {
					key uuid

					action SetValue {
						value  int32
						secret bytes { @py omit }
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").
				ToContain("class SetValuePayload(BaseModel):").
				ToNotContain("secret")
		})

		It("Should fail when a generated name hides a type of the namespace", func(
			ctx SpecContext,
		) {
			req := MustGenerateRequest(ctx, `
				@py output "client/py/synnax/counter"

				SetPayload struct {
					value int32
				}

				Counter struct {
					key uuid

					action Create {
						payload SetPayload
					}

					action Set {}
				}
			`, "counter", loader)
			Expect(p.Generate(req)).Error().To(SatisfyAll(
				MatchError(validate.ErrValidation),
				MatchError(ContainSubstring("counter.SetPayload")),
			))
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
