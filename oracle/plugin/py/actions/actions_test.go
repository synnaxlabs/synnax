package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/py/actions"
	. "github.com/synnaxlabs/oracle/testutil"
	. "github.com/synnaxlabs/x/testutil"
)

func TestPyActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin Python Actions Suite", SuiteConfig())
}

var _ = Describe("Python Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("py/actions"))
		})

		It("Should filter on py domain", func() {
			Expect(p.Domains()).To(Equal([]string{"py"}))
		})

		It("Should require py/types", func() {
			Expect(p.Requires()).To(Equal([]string{"py/types"}))
		})
	})

	Describe("Generate", func() {
		DescribeTable("Should not emit an actions_gen.py file",
			func(ctx SpecContext, source string) {
				resp := MustGenerate(ctx, source, "counter", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
			Entry("for a struct without actions", `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid
				}
			`),
			Entry("for a hand-written struct", `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Reset {}

					@py hand
				}
			`),
			Entry("for a struct with no Python output", `
				@go output "core/pkg/service/counter"

				Counter struct {
					key uuid

					action Reset {}
				}
			`),
		)

		It("Should emit one builder per action", func(ctx SpecContext) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action SetValue {
						value int32
					}

					action Reset {}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").
				ToContain(
					"# Code generated by Oracle. DO NOT EDIT.",
					"from synnax.counter.types_gen import ResetAction, ResetPayload, "+
						"SetValueAction, SetValuePayload\n",
					"def set_value(payload: SetValuePayload) -> SetValueAction:\n"+
						"    return SetValueAction(set_value=payload)",
					"def reset(payload: ResetPayload) -> ResetAction:\n"+
						"    return ResetAction(reset=payload)",
				).
				ToNotContain("class ")
		})

		It("Should emit no builder for the action that only the Core emits", func(
			ctx SpecContext,
		) {
			loader.Add("schemas/x/patch", `
				@py output "x/py/x/patch"

				Set struct { path string[] }
				Remove struct { path string[] }
				Insert struct { path string[] }
				Move struct { path string[] }
			`)
			resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					@actions
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").
				ToContain("def set(payload: SetPayload) -> SetAction:").
				ToNotContain("def create", "CreatePayload")
		})

		It("Should give a keyword action an escaped builder", func(ctx SpecContext) {
			resp := MustGenerate(ctx, `
				@py output "client/py/synnax/counter"

				Counter struct {
					key uuid

					action Import {
						from string
					}
				}
			`, "counter", loader, p)
			ExpectContent(resp, "actions_gen.py").ToContain(
				"def import_(payload: ImportPayload) -> ImportAction:\n" +
					"    return ImportAction(import_=payload)",
			)
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
