// Package actions emits a Python module of action builders for each struct or union
// that has actions. The py/types plugin emits the payload models and the Action union.
// This plugin emits one builder per action that clients dispatch.
package actions

import (
	"bytes"
	"slices"
	"strings"
	"text/template"

	"github.com/synnaxlabs/oracle/internal/casing"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/domain"
	"github.com/synnaxlabs/oracle/plugin/output"
	"github.com/synnaxlabs/oracle/plugin/py/keywords"
	pytypes "github.com/synnaxlabs/oracle/plugin/py/types"
	"github.com/synnaxlabs/oracle/resolution"
	"github.com/synnaxlabs/x/errors"
)

// Options configures the actions plugin output.
type Options struct {
	// FileNamePattern is the basename written for each output package.
	FileNamePattern string
}

// DefaultOptions returns the production defaults: actions_gen.py.
func DefaultOptions() Options {
	return Options{FileNamePattern: "actions_gen.py"}
}

// Plugin emits the generated Python action module.
type Plugin struct{ opts Options }

// New constructs a Plugin with the given options.
func New(opts Options) *Plugin { return &Plugin{opts: opts} }

func (*Plugin) Name() string       { return "py/actions" }
func (*Plugin) Domains() []string  { return []string{"py"} }
func (*Plugin) Requires() []string { return []string{"py/types"} }

// Generate emits one actions_gen.py per output package that holds a struct or union
// with actions that clients dispatch.
func (p *Plugin) Generate(req *plugin.Request) (*plugin.Response, error) {
	resp := &plugin.Response{Files: make([]plugin.File, 0)}
	for _, typ := range domain.ActionTargets(req.Resolutions, "py") {
		outputPath := output.GetPath(typ, "py")
		data, err := builders(typ, outputPath, req.Resolutions)
		if err != nil {
			return nil, err
		}
		if len(data.Builders) == 0 {
			continue
		}
		var buf bytes.Buffer
		if err := fileTemplate.Execute(&buf, data); err != nil {
			return nil, err
		}
		resp.Files = append(resp.Files, plugin.File{
			Path:    outputPath + "/" + p.opts.FileNamePattern,
			Content: buf.Bytes(),
		})
	}
	return resp, nil
}

func builders(
	typ resolution.Type,
	outputPath string,
	table *resolution.Table,
) (templateData, error) {
	union, ok := table.Get(resolution.ActionUnion(typ))
	if !ok {
		return templateData{}, errors.Newf("%s: no Action union", typ.QualifiedName)
	}
	unionName := domain.GetName(union, "py")
	data := templateData{Module: pytypes.TypesModule(outputPath)}
	var names []string
	for _, action := range typ.Actions() {
		if action.CoreOnly {
			continue
		}
		payload, ok := action.Payload.Resolve(table)
		if !ok {
			return templateData{}, errors.Newf(
				"%s: unresolved payload %s", typ.QualifiedName, action.Payload.Name,
			)
		}
		wire := casing.TypeSnake(action.Name)
		b := builderData{
			Name:    keywords.Escape(wire),
			Payload: domain.GetName(payload, "py"),
			Variant: casing.VariantTypeName(unionName, wire),
		}
		names = append(names, b.Payload, b.Variant)
		data.Builders = append(data.Builders, b)
	}
	slices.Sort(names)
	data.Names = strings.Join(slices.Compact(names), ", ")
	return data, nil
}

// templateData's fields are read by fileTemplate, so they must stay exported.
type templateData struct {
	// Module is the types module of the output package.
	Module string
	// Names are the names the module imports from Module.
	Names    string
	Builders []builderData
}

type builderData struct {
	// Name is the builder function, and the variant attribute that holds the payload.
	Name    string
	Payload string
	Variant string
}

var fileTemplate = template.Must(
	template.New("py-actions").
		Parse(`# Code generated by Oracle. DO NOT EDIT.

from __future__ import annotations

from {{ .Module }} import {{ .Names }}
{{- range .Builders }}


def {{ .Name }}(payload: {{ .Payload }}) -> {{ .Variant }}:
    return {{ .Variant }}({{ .Name }}=payload)
{{- end }}
`),
)
