package patch_test

import (
	"os"
	"path/filepath"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/analyzer"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/go/patch"
	"github.com/synnaxlabs/oracle/resolution"
	. "github.com/synnaxlabs/oracle/testutil"
	"github.com/synnaxlabs/oracle/versions"
	. "github.com/synnaxlabs/x/testutil"
)

const patchSchema = `
@go output "x/go/patch"

Set struct {
	path string[]
}
`

var _ = Describe("Go Patch Plugin", func() {
	var (
		loader *MockFileLoader
		p      *patch.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		loader.Add("schemas/x/patch", patchSchema)
		loader.Add("schemas/shade", `
			@go output "x/go/shade"

			Shade struct {
				r      uint8
				a      float64
				secret string {
					@go wire omit
				}
			}
		`)
		p = patch.New(patch.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("go/patch"))
		})

		It("Should filter on go domain", func() {
			Expect(p.Domains()).To(Equal([]string{"go"}))
		})

		It("Should require go/types", func() {
			Expect(p.Requires()).To(Equal([]string{"go/types"}))
		})
	})

	Describe("Generate", func() {
		const document = `
			import "schemas/x/patch"
			import "schemas/shade"

			@go output "core/pkg/service/doc"

			Key = uuid

			Window struct {
				start int64
				end   int64
			}

			Doc struct {
				key    Key {
					@key
				}
				name   string {
					@patch
				}
				window Window {
					@patch
				}
				shade  shade.Shade? {
					@patch
				}
				parent Key? {
					@patch
				}
				labels string[]

				action Set extends patch.Set {}
			}
		`

		It("Should switch on the @patch fields of a document", func(ctx SpecContext) {
			resp := MustGenerate(ctx, document, "doc", loader, p)
			ExpectContent(resp, "core/pkg/service/doc/patch.gen.go").
				ToBeValidGoSource().
				ToContain(
					"// Code generated by oracle. DO NOT EDIT.",
					"package doc",
					`import "github.com/synnaxlabs/x/patch"`,
					"func (d *Doc) Patch(c patch.Cursor) error {",
					`case "name":`,
					"return patch.Value(&d.Name, c.Next())",
					`case "window":`,
					"return patch.Value(&d.Window, c)",
					"return d.Window.Patch(c)",
					`case "shade":`,
					"if c = c.Next(); c.Done() || d.Shade == nil {",
					"return patch.OptionalValue(&d.Shade, c)",
					"next := *d.Shade",
					"if err := next.Patch(c); err != nil {",
					"d.Shade = &next",
					`case "parent":`,
					"return patch.OptionalValue(&d.Parent, c.Next())",
					"return c.UnknownField()",
				).
				ToNotContain(`case "key":`, `case "labels":`)
		})

		It(
			"Should find a document whose Set action aliases patch.Set",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
					import "schemas/x/patch"

					@go output "core/pkg/service/doc"

					Doc struct {
						name string {
							@patch
						}

						action Set = patch.Set
					}
				`, "doc", loader, p)
				ExpectContent(resp, "core/pkg/service/doc/patch.gen.go").ToContain(
					"func (d *Doc) Patch(c patch.Cursor) error {",
					`case "name":`,
				)
			},
		)

		It(
			"Should switch on every field of a struct a document reaches",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, document, "doc", loader, p)
				ExpectContent(resp, "core/pkg/service/doc/patch.gen.go").ToContain(
					"func (w *Window) Patch(c patch.Cursor) error {",
					"return patch.Value(&w.Start, c.Next())",
					"return patch.Value(&w.End, c.Next())",
				)
				ExpectContent(resp, "x/go/shade/patch.gen.go").
					ToBeValidGoSource().
					ToContain(
						"package shade",
						"func (s *Shade) Patch(c patch.Cursor) error {",
						"return patch.Value(&s.R, c.Next())",
						"return patch.Value(&s.A, c.Next())",
					).
					ToNotContain(`case "secret":`)
			},
		)

		It(
			"Should reset a removed field that has a default to that default",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/scale"

				Linear struct {
					slope  float64 = 1
					offset float64 = 0
				}

				Doc struct {
					scale Linear {
						@patch
					}
					name  string {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "scale", loader, p)
				ExpectContent(resp, "patch.gen.go").
					ToBeValidGoSource().
					ToContain(
						"return patch.Defaulted(&l.Slope, c.Next(), func(def *Linear) {",
						"l.Slope = def.Slope",
						"return patch.Value(&l.Offset, c.Next())",
						"return patch.Defaulted(&d.Scale, c, func(def *Doc) {",
						"d.Scale = def.Scale",
						"return patch.Value(&d.Name, c.Next())",
					)
			},
		)

		It(
			"Should reset a removed field only when its default sets a value",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/mode"

				Mode enum {
					fast = "fast"
					slow = "slow"
				}

				Level enum {
					low  = 0
					high = 1
				}

				Doc struct {
					key string = create {
						@patch
					}
					level Level = low {
						@patch
					}
					mode Mode = slow {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "mode", loader, p)
				ExpectContent(resp, "patch.gen.go").
					ToBeValidGoSource().
					ToContain(
						"return patch.Value(&d.Key, c.Next())",
						"return patch.Value(&d.Level, c.Next())",
						"return patch.Defaulted(&d.Mode, c.Next(), func(def *Doc) {",
					)
			},
		)

		It(
			"Should decide a reset by the kind of the default",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/source"

				Source union on type {
					internal {}
					external {
						port int32
					}
				}

				Plain struct {
					rate float64
				}

				Pair struct {
					a Plain
					b Plain
				}

				Doc struct {
					source Source = internal {
						@patch
					}
					rate float64 = 0.0 {
						@patch
					}
					origin Plain = { rate = 2 } {
						@patch
					}
					enabled bool = false {
						@patch
					}
					tags string[] = [] {
						@patch
					}
					pair Pair {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "source", loader, p)
				ExpectContent(resp, "patch.gen.go").
					ToBeValidGoSource().
					ToContain(
						"return patch.Defaulted(&d.Source, c, func(def *Doc) {",
						"return patch.Value(&d.Rate, c.Next())",
						"return patch.Defaulted(&d.Origin, c, func(def *Doc) {",
						"return patch.Value(&d.Enabled, c.Next())",
					).
					ToNotContain(
						"patch.Defaulted(&d.Tags",
						"patch.Defaulted(&d.Pair",
					)
			},
		)

		It(
			"Should give a receiver that the cursor does not shadow",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/cell"

				Cell struct {
					name string {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "cell", loader, p)
				ExpectContent(resp, "patch.gen.go").
					ToContain("func (cv *Cell) Patch(c patch.Cursor) error {")
			},
		)

		It(
			"Should set a struct with a hand-written JSON decoder only as a whole",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/doc"

				Tint struct {
					r uint8
					a float64

					@go json hand
				}

				Doc struct {
					tint Tint {
						@patch
					}
					glow Tint? {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "doc", loader, p)
				ExpectContent(resp, "core/pkg/service/doc/patch.gen.go").
					ToBeValidGoSource().
					ToContain(
						"return patch.Value(&d.Tint, c.Next())",
						"return patch.OptionalValue(&d.Glow, c.Next())",
					).
					ToNotContain("func (t *Tint) Patch(")
			},
		)

		It(
			"Should not generate for a struct without path actions",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				@go output "core/pkg/service/doc"

				New struct {
					name string {
						@patch
					}
				}
			`, "doc", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
		)

		It(
			"Should delete the patch file of a package with no Patch methods",
			func(ctx SpecContext) {
				resp := MustGenerate(ctx, `
				@go output "core/pkg/service/doc"

				Doc struct {
					name string
				}
			`, "doc", loader, p)
				Expect(resp.Files).To(BeEmpty())
				Expect(
					resp.Deletions,
				).To(ContainElement("core/pkg/service/doc/patch.gen.go"))
			},
		)

		DescribeTable("Should reject a field that path actions cannot edit",
			func(ctx SpecContext, field, msg string) {
				req := MustGenerateRequest(ctx, `
					import "schemas/x/patch"

					@go output "core/pkg/service/doc"

					Doc struct {
						`+field+`

						action Set extends patch.Set {}
					}
				`, "doc", loader)
				Expect(p.Generate(req)).Error().To(MatchError(ContainSubstring(msg)))
			},
			Entry(
				"an optional list",
				"tags string[]? {\n@patch\n}",
				"doc.Doc.tags: path actions do not support an optional list or map",
			),
			Entry(
				"a field without a JSON form",
				"secret string {\n@patch\n@go wire omit\n}",
				"doc.Doc.secret: a field without a JSON form cannot be @patch",
			),
		)

		It(
			"Should reject a document that another document reaches",
			func(ctx SpecContext) {
				req := MustGenerateRequest(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/doc"

				Inner struct {
					name string {
						@patch
					}

					action Set extends patch.Set {}
				}

				Outer struct {
					inner Inner {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "doc", loader)
				Expect(p.Generate(req)).Error().To(MatchError(ContainSubstring(
					"doc.Inner is a document, so no other document can hold it",
				)))
			},
		)
	})

	Describe("Store documents", func() {
		const store = `
			@go output "core/pkg/service/cfg"

			Mode enum {
				fast = "fast"
				slow = "slow"
			}

			Rate float64

			Range struct {
				min float64
				max float64
			}

			Scale struct {
				scale float64
			}

			Base struct {
				key  string
				port string
			}

			Channel union on type extends Base {
				analog extends Range, Scale {
					port string = "AIN0"
					gain float64
				}
				digital {
					line int32
				}
			}

			Entry struct {
				key   string
				name  string
				modes Mode[]
			}

			Point struct {
				x float64
			}

			Config struct {
				key      uuid
				rate     Rate
				mode     Mode
				label    string?
				channels Channel[]
				entries  Entry[]
				points   Point[]
				payload  any
				fill     any?
				id       uuid

				@patch
			}
		`

		It("Should switch on every field of a document with @patch", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, store, "cfg", loader, p)
			ExpectContent(resp, "core/pkg/service/cfg/patch.gen.go").
				ToBeValidGoSource().
				ToContain(
					"func (cv *Config) Patch(c patch.Cursor) error {",
					"return patch.Value(&cv.Key, c.Next())",
					"return patch.Value(&cv.Rate, c.Next())",
					"return patch.OptionalValue(&cv.Label, c.Next())",
					"return patch.List(&cv.Channels, c.Next())",
					"return patch.List(&cv.Entries, c.Next())",
					"return patch.Value(&cv.Points, c.Next())",
					"return patch.Any(&cv.Payload, c.Next())",
					"return patch.OptionalAny(&cv.Fill, c.Next())",
				).
				ToNotContain("func (p *Point) Patch", "func (p *Point) PatchKey")
		})

		It("Should apply an action to the active variant of a union", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, store, "cfg", loader, p)
			ExpectContent(resp, "core/pkg/service/cfg/patch.gen.go").ToContain(
				"func (cv *Channel) Patch(c patch.Cursor) error {",
				"switch v := cv.Variant.(type) {",
				"case AnalogChannel:",
				`c, ok := c.Guard("type", "analog")`,
				`if c.Segment() == "type" {`,
				"return patch.Discriminator(cv, c)",
				"if err := v.Patch(c); err != nil {",
				"cv.Variant = v",
				`return patch.Absent(cv, c, "type")`,
				"func (ac *AnalogChannel) Patch(c patch.Cursor) error {",
				"func (dc *DigitalChannel) Patch(c patch.Cursor) error {",
			)
		})

		It("Should reach a field through the parents that a variant embeds", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, store, "cfg", loader, p)
			ExpectContent(resp, "core/pkg/service/cfg/patch.gen.go").ToContain(
				"return patch.Value(&ac.Base.Key, c.Next())",
				"return patch.Defaulted(&ac.Base.Port, c.Next(), func(def *AnalogChannel) {",
				"ac.Base.Port = def.Base.Port",
				"return patch.Value(&ac.Range.Min, c.Next())",
				"return patch.Value(&ac.Scale.Scale, c.Next())",
				"return patch.Value(&ac.Gain, c.Next())",
			)
		})

		It("Should name the entries of a keyed list by their key", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, store, "cfg", loader, p)
			ExpectContent(resp, "core/pkg/service/cfg/patch.gen.go").ToContain(
				"func (e *Entry) PatchKey() string { return e.Key }",
				"func (cv *Channel) PatchKey() string {",
				"case AnalogChannel:\n\t\treturn v.Base.Key",
			)
		})

		It("Should hash every value of a document except its keys", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, store, "cfg", loader, p)
			ExpectContent(resp, "core/pkg/service/cfg/patch.gen.go").
				ToContain(
					"func (cv *Config) HashContent(h *content.Hash) {",
					"h.Float(float64(cv.Rate))",
					"h.String(string(cv.Mode))",
					"if cv.Label == nil {",
					"h.String(*cv.Label)",
					"h.Len(len(cv.Channels))",
					"cv.Channels[i0].HashContent(h)",
					"for i0 := range e.Modes {",
					"h.String(string(e.Modes[i0]))",
					"h.Any(cv.Payload)",
					"h.Any(*cv.Fill)",
					"h.Bytes(cv.ID[:])",
					"func (cv *Channel) HashContent(h *content.Hash) {",
					`h.String("analog")`,
					"func (p *Point) HashContent(h *content.Hash) {",
					"h.Float(ac.Range.Min)",
				).
				ToNotContain("h.Bytes(cv.Key[:])", "h.String(e.Key)")
		})

		It("Should leave the hash out for a document with @patch fields", func(
			ctx SpecContext,
		) {
			resp := MustGenerate(ctx, `
				import "schemas/x/patch"

				@go output "core/pkg/service/cell"

				Cell struct {
					name string {
						@patch
					}

					action Set extends patch.Set {}
				}
			`, "cell", loader, p)
			ExpectContent(resp, "core/pkg/service/cell/patch.gen.go").
				ToNotContain("HashContent", "x/content")
		})

		DescribeTable("Should reject a value that the hash cannot write",
			func(ctx SpecContext, field, msg string) {
				req := MustGenerateRequest(ctx, `
					@go output "core/pkg/service/cfg"

					Config struct {
						`+field+`

						@patch
					}
				`, "cfg", loader)
				Expect(p.Generate(req)).Error().To(MatchError(ContainSubstring(msg)))
			},
			Entry(
				"a map",
				"tags map<string, string>",
				"content hashing does not support a map",
			),
		)
	})

	Describe("Version chains", func() {
		It(
			"Should generate each method in the version that declares its struct",
			func() {
				root := GinkgoT().TempDir()
				write := func(rel, content string) {
					GinkgoHelper()
					full := filepath.Join(root, rel)
					Expect(os.MkdirAll(filepath.Dir(full), 0o755)).To(Succeed())
					Expect(os.WriteFile(full, []byte(content), 0o644)).To(Succeed())
				}
				write("schemas/x/patch.oracle", patchSchema)
				write("schemas/synnax/versions/doc/v0.oracle", `
Shade struct {
	r uint8
}

Doc struct {
	name string
	shade Shade
}
`)
				write("schemas/synnax/versions/doc/v1.oracle", `
Shade = v0.Shade

Doc struct {
	name string
	shade Shade
	note string
}
`)
				write("core/pkg/service/doc/versions/v0/patch.gen.go", "package v0\n")
				chains := MustSucceed(versions.Discover(root))
				resolver := versions.NewResolver(
					chains,
					analyzer.NewStandardFileLoader(root),
				)
				table := resolution.NewTable()
				diag := analyzer.AnalyzeSeeded(
					GinkgoT().Context(), `
import "schemas/x/patch"

@go output "core/pkg/service/doc"

Shade struct {
	r uint8
}

Doc struct {
	name string {
		@patch
	}
	shade Shade {
		@patch
	}
	note string

	action Set extends patch.Set {}
}
`,
					"schemas/synnax/doc.oracle", "doc",
					analyzer.NewStandardFileLoader(root), table,
				)
				Expect(diag.Ok()).To(BeTrue(), diag.String())
				resp := MustSucceed(p.Generate(&plugin.Request{
					Resolutions: table, RepoRoot: root, Versions: resolver,
				}))
				ExpectContent(resp, "core/pkg/service/doc/versions/v1/patch.gen.go").
					ToContain(
						"package v1",
						"func (d *Doc) Patch(c patch.Cursor) error {",
					).
					ToNotContain("Shade) Patch")
				ExpectContent(resp, "core/pkg/service/doc/versions/v0/patch.gen.go").
					ToContain(
						"package v0",
						"func (s *Shade) Patch(c patch.Cursor) error {",
					).
					ToNotContain("Doc) Patch")
				Expect(
					resp.Deletions,
				).To(ContainElement("core/pkg/service/doc/patch.gen.go"))
				Expect(resp.Deletions).ToNot(ContainElement(
					"core/pkg/service/doc/versions/v0/patch.gen.go",
				))
			},
		)
	})
})
