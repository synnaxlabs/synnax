// chainRequestFor writes a version chain for resource under root and returns
// the request the plugin reads it through: the chain dates the resource's
// export history and supplies its current version.
func chainRequestFor(
	ctx context.Context, root, resource, live string, chain map[int]string,
) *plugin.Request {
	GinkgoHelper()
	dir := filepath.Join(root, "schemas", "synnax", "versions", resource)
	Expect(os.MkdirAll(dir, 0o755)).To(Succeed())
	for n, src := range chain {
		Expect(os.WriteFile(
			filepath.Join(dir, fmt.Sprintf("v%d.oracle", n)), []byte(src), 0o644,
		)).To(Succeed())
	}
	loader := analyzer.NewStandardFileLoader(root)
	table := resolution.NewTable()
	diag := analyzer.AnalyzeSeeded(
		ctx, live, "schemas/synnax/"+resource+".oracle", resource, loader, table,
	)
	Expect(diag.Ok()).To(BeTrue(), diag.String())
	return &plugin.Request{
		Resolutions: table,
		RepoRoot:    root,
		Versions: versions.NewResolver(
			MustSucceed(versions.Discover(root)), loader,
		),
	}
}

func chainRequest(
	ctx context.Context, root, live string, chain map[int]string,
) *plugin.Request {
	GinkgoHelper()
	return chainRequestFor(ctx, root, "log", live, chain)
}

// logChain is one version file's persisted Log surface. imex marks an exported version.
func logChain(exported bool) string {
	marker := ""
	if exported {
		marker = "\n\t@go imex"
	}
	return fmt.Sprintf(
		"Log struct {\n\tkey uuid @key\n\tname string%s\n}\n", marker,
	)
}

// liveLog is the live schema, exported. The chain supplies the version.
const liveLog = `
@go output "core/pkg/service/log"

Log struct {
	key  uuid @key
	name string
	@go imex
}
`

var _ = Describe("Go ImEx Plugin", func() {
	var (
		loader *MockFileLoader
		p      *imex.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = imex.New(imex.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("go/imex"))
		})

		It("Should filter on go domain", func() {
			Expect(p.Domains()).To(Equal([]string{"go"}))
		})

		It("Should require go/types", func() {
			Expect(p.Requires()).To(Equal([]string{"go/types"}))
		})
	})

	Describe("Options validation", func() {
		It("Should error when no runtime import path is configured", func() {
			bare := imex.New(imex.Options{FileNamePattern: "imex.gen.go"})
			Expect(bare.Generate(nil)).Error().To(MatchError(
				ContainSubstring("go/imex requires Options.RuntimeImportPath"),
			))
		})

		It("Should error when no ontology import path is configured", func() {
			opts := imex.DefaultOptions()
			opts.OntologyImportPath = ""
			Expect(imex.New(opts).Generate(nil)).Error().To(MatchError(
				ContainSubstring("go/imex requires Options.OntologyImportPath"),
			))
		})
	})

	Describe("Generate", func() {
		It(
			"Should emit no files when no type declares the marker",
			func(ctx SpecContext) {
				source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
				}
			`
				resp := MustGenerate(ctx, source, "log", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
		)

		It(
			"Should emit the current version constant and Latest",
			func(ctx SpecContext) {
				req := chainRequest(
					ctx, GinkgoT().TempDir(), liveLog,
					map[int]string{3: logChain(true)},
				)
				resp := MustSucceed(p.Generate(req))
				Expect(resp.Files).To(HaveLen(3))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/v3/imex.gen.go",
				).ToContain(
					"// Code generated by oracle. DO NOT EDIT.",
					"package v3",
					`import "github.com/synnaxlabs/synnax/pkg/service/imex"`,
					"const Version imex.Version = 3",
				).
					ToBeValidGoSource()
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"package versions",
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions/v3"`,
					"const Latest = v3.Version",
					"func autoDecodeEnvelope(ctx context.Context, env imex.Envelope) (Log, error)",
					"case v3.Version:",
					"return env.Decode[Log](ctx)",
					"func liftFirst(ctx context.Context, t3 v3.Log) (Log, error) {\n"+
						"\treturn t3, nil\n}",
				).
					ToBeValidGoSource()
				ExpectContent(resp, "core/pkg/service/log/imex.gen.go").ToContain(
					"package log",
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions"`,
					`"github.com/synnaxlabs/synnax/pkg/service/ontology"`,
					"func (s *Service) Export(ctx context.Context, id ontology.ID) "+
						"(imex.Envelope, error)",
					"var v Log",
					"Where(MatchKeys(key))",
					"Version: versions.Latest, Type: string(s.Type()), Name: v.Name,",
					"env.Encode(v)",
				).ToBeValidGoSource()
			},
		)

		It(
			"Should delete constants in version directories below the floor",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				diskLoader := NewMockFileLoaderWithRoot(tmpDir)
				for _, dir := range []string{"v2", "v3", "legacy", "testdata"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir,
							"core/pkg/service/log/versions",
							dir,
						),
						0o755,
					)).To(Succeed())
				}
				_ = diskLoader
				req := chainRequest(
					ctx, tmpDir, liveLog, map[int]string{3: logChain(true)},
				)
				resp := MustSucceed(p.Generate(req))
				Expect(resp.Files).To(HaveLen(3))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/v3/imex.gen.go",
				).ToContain(
					"package v3",
					"const Version imex.Version = 3",
				).
					ToBeValidGoSource()
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"const Latest = v3.Version",
				).
					ToBeValidGoSource()
				Expect(resp.Deletions).To(ConsistOf(
					"core/pkg/service/log/versions/v2/imex.gen.go",
				))
			},
		)

		It("Should derive packages from a nested output path", func(ctx SpecContext) {
			live := `
@go output "core/pkg/service/schematic/symbol"

Symbol struct {
	key  uuid @key
	name string
	@go imex
}
`
			req := chainRequestFor(
				ctx,
				GinkgoT().TempDir(),
				"symbol",
				live,
				map[int]string{
					1: "Symbol struct {\n\tkey uuid @key\n\n\t@go imex\n}\n",
				},
			)
			resp := MustSucceed(p.Generate(req))
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/v1/imex.gen.go",
			).ToContain(
				"package v1",
				"const Version imex.Version = 1",
			).ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/imex.gen.go",
			).ToContain(
				"package versions",
				`"github.com/synnaxlabs/synnax/core/pkg/service/schematic/symbol/versions/v1"`,
				"const Latest = v1.Version",
			).
				ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/imex.gen.go",
			).ToContain(
				"package symbol",
				`"github.com/synnaxlabs/synnax/core/pkg/service/schematic/symbol/versions"`,
				"var v Symbol",
			).
				ToBeValidGoSource()
		})

		It(
			"Should extend the ladder back to the first version carrying the marker",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir, "core/pkg/service/log/versions", dir,
						),
						0o755,
					)).To(Succeed())
				}
				Expect(os.WriteFile(
					filepath.Join(
						tmpDir,
						"core/pkg/service/log/versions/v3/migrate.go",
					),
					[]byte("package v3\n\nfunc MigrateLog() {}\n"),
					0o644,
				)).To(Succeed())
				req := chainRequest(ctx, tmpDir, liveLog, map[int]string{
					2: logChain(true),
					3: logChain(true),
				})
				resp := MustSucceed(p.Generate(req))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions/v2"`,
					"case v2.Version:",
					"t2, err := env.Decode[v2.Log](ctx)",
					"t3, err := v3.MigrateLog(ctx, t2)",
					"return t3, nil",
					"func liftFirst(ctx context.Context, t2 v2.Log) (Log, error) {\n"+
						"\tt3, err := v3.MigrateLog(ctx, t2)\n"+
						"\tif err != nil {\n\t\treturn Log{}, err\n\t}\n"+
						"\treturn t3, nil\n}",
				).
					ToBeValidGoSource()
			},
		)

		It(
			"Should pass alias-only bumps through without a migrate step",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir, "core/pkg/service/log/versions", dir,
						),
						0o755,
					)).To(Succeed())
				}
				req := chainRequest(ctx, tmpDir, liveLog, map[int]string{
					2: logChain(true),
					3: "Log = v2.Log\n",
				})
				resp := MustSucceed(p.Generate(req))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"case v2.Version:",
					"t2, err := env.Decode[v2.Log](ctx)",
					"return t2, nil",
					"func liftFirst(ctx context.Context, t2 v2.Log) (Log, error) {\n"+
						"\treturn t2, nil\n}",
				).
					ToBeValidGoSource()
			},
		)

		It(
			"Should error when a version redeclares the type without a migrate step",
			func(ctx SpecContext) {
				req := chainRequest(ctx, GinkgoT().TempDir(), liveLog, map[int]string{
					2: logChain(true),
					3: logChain(true),
				})
				Expect(p.Generate(req)).Error().To(MatchError(
					"core/pkg/service/log/versions/v3 redeclares log.Log without the " +
						"MigrateLog step its import ladder needs",
				))
			},
		)

		It(
			"Should floor at the current version when earlier versions lack the marker",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				req := chainRequest(ctx, tmpDir, liveLog, map[int]string{
					2: logChain(false),
					3: logChain(true),
				})
				resp := MustSucceed(p.Generate(req))
				content := MustContentOf(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				)
				Expect(content).To(ContainSubstring("const Latest = v3.Version"))
				Expect(content).ToNot(ContainSubstring("case v2.Version:"))
			},
		)

		It("Should import the configured runtime package", func(ctx SpecContext) {
			custom := imex.New(imex.Options{
				FileNamePattern:    "imex.gen.go",
				RuntimeImportPath:  "github.com/acme/portable/imex",
				OntologyImportPath: "github.com/acme/portable/ontology",
			})
			req := chainRequest(
				ctx, GinkgoT().TempDir(), liveLog,
				map[int]string{3: logChain(true)},
			)
			resp := MustSucceed(custom.Generate(req))
			ExpectContent(
				resp, "core/pkg/service/log/versions/v3/imex.gen.go",
			).ToContain(`import "github.com/acme/portable/imex"`).ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/log/versions/imex.gen.go",
			).ToContain(`"github.com/acme/portable/imex"`).ToBeValidGoSource()
		})

		It(
			"Should error when a version package does not parse",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(tmpDir, "core/pkg/service/log/versions", dir),
						0o755,
					)).To(Succeed())
				}
				Expect(os.WriteFile(
					filepath.Join(
						tmpDir, "core/pkg/service/log/versions/v3/migrate.go",
					),
					[]byte("package v3\n\nfunc MigrateLog( {\n"),
					0o644,
				)).To(Succeed())
				req := chainRequest(ctx, tmpDir, liveLog, map[int]string{
					2: logChain(true),
					3: logChain(true),
				})
				Expect(p.Generate(req)).Error().To(MatchError(
					ContainSubstring(filepath.FromSlash("versions/v3/migrate.go")),
				))
			},
		)

		It("Should error when the chain leaves a marked type unversioned", func(
			ctx SpecContext,
		) {
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key uuid
					@go imex
				}
			`
			req := MustGenerateRequest(ctx, source, "log", loader)
			Expect(p.Generate(req)).Error().To(MatchError(
				ContainSubstring("@go imex without a version chain"),
			))
		})

		Describe("Body", func() {
			// configChain is one version file's persisted surface of two task configs.
			configChain := func(marker string) string {
				return fmt.Sprintf(
					"ReadConfig struct {\n\tkey uuid @key\n\trate int32%[1]s\n}\n\n"+
						"ScanConfig struct {\n\tkey uuid @key%[1]s\n}\n",
					marker,
				)
			}
			const liveConfigs = `
@go output "core/pkg/service/modbus"

ReadConfig struct {
	key  uuid @key
	rate int32
	@go imex body
}

ScanConfig struct {
	key uuid @key
	@go imex body
}
`
			configRequest := func(
				ctx context.Context, root string, chain map[int]string,
			) *plugin.Request {
				GinkgoHelper()
				return chainRequestFor(ctx, root, "modbus", liveConfigs, chain)
			}

			It("Should emit a ladder per type and no Export", func(ctx SpecContext) {
				req := configRequest(ctx, GinkgoT().TempDir(), map[int]string{
					1: configChain("\n\t@go imex body"),
				})
				resp := MustSucceed(p.Generate(req))
				Expect(resp.Files).To(HaveLen(2))
				ExpectContent(
					resp, "core/pkg/service/modbus/versions/v1/imex.gen.go",
				).ToContain(
					"// Version is the portable schema version of the shapes this "+
						"package defines.",
					"const Version imex.Version = 1",
				).ToBeValidGoSource()
				ExpectContent(
					resp, "core/pkg/service/modbus/versions/imex.gen.go",
				).ToContain(
					`"github.com/synnaxlabs/x/encoding/msgpack"`,
					"const Latest = v1.Version",
					"var ReadConfigLadder = imex.Ladder[ReadConfig]{",
					"First:  v1.Version,",
					"Decode: decodeReadConfig,",
					"var ScanConfigLadder = imex.Ladder[ScanConfig]{",
					"case v1.Version:",
					`return imex.DecodeBlob[ReadConfig](data, "modbus.ReadConfig", `+
						"version)",
					`return ReadConfig{}, imex.NewErrUnsupportedVersion(`+
						`"modbus.ReadConfig", version, Latest)`,
				).ToNotContain("liftFirst").ToBeValidGoSource()
			})

			It(
				"Should delete the Export a bare marker generated for the package",
				func(ctx SpecContext) {
					req := configRequest(ctx, GinkgoT().TempDir(), map[int]string{
						1: configChain("\n\t@go imex body"),
					})
					resp := MustSucceed(p.Generate(req))
					Expect(resp.Deletions).To(ConsistOf(
						"core/pkg/service/modbus/imex.gen.go",
					))
				},
			)

			It(
				"Should migrate each type from its own first exported version",
				func(ctx SpecContext) {
					tmpDir := GinkgoT().TempDir()
					for _, dir := range []string{"v1", "v2"} {
						Expect(os.MkdirAll(
							filepath.Join(
								tmpDir,
								"core/pkg/service/modbus/versions",
								dir,
							),
							0o755,
						)).To(Succeed())
					}
					Expect(os.WriteFile(
						filepath.Join(
							tmpDir, "core/pkg/service/modbus/versions/v2/migrate.go",
						),
						[]byte("package v2\n\nfunc MigrateReadConfig() {}\n"),
						0o644,
					)).To(Succeed())
					req := configRequest(ctx, tmpDir, map[int]string{
						1: configChain("\n\t@go imex body"),
						2: "ReadConfig struct {\n\tkey uuid @key\n\trate int64\n\n" +
							"\t@go imex body\n}\n\nScanConfig = v1.ScanConfig\n",
					})
					resp := MustSucceed(p.Generate(req))
					ExpectContent(
						resp, "core/pkg/service/modbus/versions/imex.gen.go",
					).ToContain(
						"const Latest = v2.Version",
						`t1, err := imex.DecodeBlob[v1.ReadConfig](data, `+
							`"modbus.ReadConfig", version)`,
						"t2, err := v2.MigrateReadConfig(ctx, t1)",
						`t1, err := imex.DecodeBlob[v1.ScanConfig](data, `+
							`"modbus.ScanConfig", version)`,
						"return t1, nil",
					).ToBeValidGoSource()
				},
			)

			It("Should start a type's ladder at its first marked version", func(
				ctx SpecContext,
			) {
				req := configRequest(ctx, GinkgoT().TempDir(), map[int]string{
					1: "ReadConfig struct {\n\tkey uuid @key\n\trate int32\n}\n\n" +
						"ScanConfig struct {\n\tkey uuid @key\n\n\t@go imex body\n}\n",
					2: "ReadConfig struct {\n\tkey uuid @key\n\trate int64\n\n" +
						"\t@go imex body\n}\n\nScanConfig = v1.ScanConfig\n",
				})
				resp := MustSucceed(p.Generate(req))
				ExpectContent(
					resp, "core/pkg/service/modbus/versions/imex.gen.go",
				).ToContain(
					"var ReadConfigLadder = imex.Ladder[ReadConfig]{\n\tFirst:  v2.Version,",
					"var ScanConfigLadder = imex.Ladder[ScanConfig]{\n\tFirst:  v1.Version,",
				).
					ToBeValidGoSource()
			})

			It(
				"Should error when a bare marker shares a package with a body type",
				func(
					ctx SpecContext,
				) {
					live := `
@go output "core/pkg/service/modbus"

ReadConfig struct {
	key  uuid @key
	rate int32
	@go imex
}

ScanConfig struct {
	key uuid @key
	@go imex body
}
`
					req := chainRequestFor(
						ctx, GinkgoT().TempDir(), "modbus", live, map[int]string{
							1: "ReadConfig struct {\n\tkey uuid @key\n\trate int32\n\n" +
								"\t@go imex\n}\n\nScanConfig struct {\n\tkey uuid @key\n\n" +
								"\t@go imex body\n}\n",
						},
					)
					Expect(p.Generate(req)).Error().To(MatchError(ContainSubstring(
						"duplicate @go imex declarations for core/pkg/service/modbus",
					)))
				},
			)

			It("Should error when body types at one path span version chains", func(
				ctx SpecContext,
			) {
				root := GinkgoT().TempDir()
				other := filepath.Join(root, "schemas", "synnax", "versions", "other")
				Expect(os.MkdirAll(other, 0o755)).To(Succeed())
				Expect(os.WriteFile(
					filepath.Join(other, "v1.oracle"),
					[]byte(
						"OtherConfig struct {\n\tkey uuid @key\n\n\t@go imex body\n}\n",
					),
					0o644,
				)).To(Succeed())
				req := configRequest(ctx, root, map[int]string{
					1: configChain("\n\t@go imex body"),
				})
				const liveOther = `
@go output "core/pkg/service/modbus"

OtherConfig struct {
	key uuid @key
	@go imex body
}
`
				diag := analyzer.AnalyzeSeeded(
					ctx,
					liveOther,
					"schemas/synnax/other.oracle",
					"other",
					analyzer.NewStandardFileLoader(root),
					req.Resolutions,
				)
				Expect(diag.Ok()).To(BeTrue(), diag.String())
				Expect(p.Generate(req)).Error().To(MatchError(ContainSubstring(
					"@go imex body types for core/pkg/service/modbus span version chains",
				)))
			})
		})

		It(
			"Should error when two types at one path both declare the marker",
			func(ctx SpecContext) {
				live := `
@go output "core/pkg/service/log"

Log struct {
	key uuid @key
	@go imex
}

Sibling struct {
	key uuid @key
	@go imex
}
`
				req := chainRequest(
					ctx, GinkgoT().TempDir(), live,
					map[int]string{3: logChain(true)},
				)
				Expect(p.Generate(req)).Error().To(MatchError(
					ContainSubstring("duplicate @go imex declarations"),
				))
			},
		)
	})
})
