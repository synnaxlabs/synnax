package imex_test

import (
	"os"
	"path/filepath"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/go/imex"
	. "github.com/synnaxlabs/oracle/testutil"
)

var _ = Describe("Go ImEx Plugin", func() {
	var (
		loader *MockFileLoader
		p      *imex.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = imex.New(imex.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("go/imex"))
		})

		It("Should filter on go domain", func() {
			Expect(p.Domains()).To(Equal([]string{"go"}))
		})

		It("Should require go/types", func() {
			Expect(p.Requires()).To(Equal([]string{"go/types"}))
		})
	})

	Describe("Generate", func() {
		It("Should emit no files when no type declares the marker", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
				}
			`
			resp := MustGenerate(ctx, source, "log", loader, p)
			Expect(resp.Files).To(BeEmpty())
		})

		It("Should emit the current version constant and Latest", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "log", loader, p)
			Expect(resp.Files).To(HaveLen(2))
			ExpectContent(resp, "core/pkg/service/log/versions/v3/imex.gen.go").ToContain(
				"// Code generated by oracle. DO NOT EDIT.",
				"package v3",
				`import "github.com/synnaxlabs/synnax/pkg/service/imex"`,
				"const Version imex.Version = 3",
			).ToBeValidGoSource()
			ExpectContent(resp, "core/pkg/service/log/versions/imex.gen.go").ToContain(
				"package versions",
				`import "github.com/synnaxlabs/synnax/core/pkg/service/log/versions/v3"`,
				"const Latest = v3.Version",
			).ToBeValidGoSource()
		})

		It("Should request deletion of the legacy package-root constant", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "log", loader, p)
			Expect(resp.Deletions).To(
				ConsistOf("core/pkg/service/log/imex.gen.go"),
			)
		})

		It("Should emit constants for version directories present on disk", func(ctx SpecContext) {
			tmpDir := GinkgoT().TempDir()
			diskLoader := NewMockFileLoaderWithRoot(tmpDir)
			for _, dir := range []string{"v2", "v3", "legacy", "testdata"} {
				Expect(os.MkdirAll(
					filepath.Join(tmpDir, "core/pkg/service/log/versions", dir), 0o755,
				)).To(Succeed())
			}
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "log", diskLoader, p)
			Expect(resp.Files).To(HaveLen(3))
			ExpectContent(resp, "core/pkg/service/log/versions/v2/imex.gen.go").ToContain(
				"package v2",
				"const Version imex.Version = 2",
			).ToBeValidGoSource()
			ExpectContent(resp, "core/pkg/service/log/versions/v3/imex.gen.go").ToContain(
				"package v3",
				"const Version imex.Version = 3",
			).ToBeValidGoSource()
			ExpectContent(resp, "core/pkg/service/log/versions/imex.gen.go").ToContain(
				"const Latest = v3.Version",
			).ToBeValidGoSource()
		})

		It("Should derive packages from a nested output path", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/schematic/symbol"

				Symbol struct {
					key  uuid
					name string
					@go version 1
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "symbol", loader, p)
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/v1/imex.gen.go",
			).ToContain(
				"package v1",
				"const Version imex.Version = 1",
			).ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/imex.gen.go",
			).ToContain(
				"package versions",
				`import "github.com/synnaxlabs/synnax/core/pkg/service/schematic/symbol/versions/v1"`,
				"const Latest = v1.Version",
			).ToBeValidGoSource()
		})

		It("Should error when two types at one path both declare the marker", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key uuid
					@go version 3
					@go imex
				}

				Sibling struct {
					key uuid
					@go version 3
					@go imex
				}
			`
			req := MustGenerateRequest(ctx, source, "log", loader)
			Expect(p.Generate(req)).Error().To(MatchError(
				ContainSubstring("duplicate @go imex declarations"),
			))
		})
	})
})
