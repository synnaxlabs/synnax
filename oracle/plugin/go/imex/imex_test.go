package imex_test

import (
	"os"
	"path/filepath"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/go/imex"
	"github.com/synnaxlabs/oracle/resolution"
	. "github.com/synnaxlabs/oracle/testutil"
	"github.com/synnaxlabs/x/errors"
	. "github.com/synnaxlabs/x/testutil"
)

var _ = Describe("Go ImEx Plugin", func() {
	var (
		loader *MockFileLoader
		p      *imex.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = imex.New(imex.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("go/imex"))
		})

		It("Should filter on go domain", func() {
			Expect(p.Domains()).To(Equal([]string{"go"}))
		})

		It("Should require go/types", func() {
			Expect(p.Requires()).To(Equal([]string{"go/types"}))
		})
	})

	Describe("Check", func() {
		It("Should pass with the default runtime import path", func() {
			Expect(p.Check(nil)).To(Succeed())
		})

		It("Should error when no runtime import path is configured", func() {
			bare := imex.New(imex.Options{FileNamePattern: "imex.gen.go"})
			Expect(bare.Check(nil)).To(MatchError(
				ContainSubstring("go/imex requires Options.RuntimeImportPath"),
			))
		})

		It("Should error when no ontology import path is configured", func() {
			opts := imex.DefaultOptions()
			opts.OntologyImportPath = ""
			Expect(imex.New(opts).Check(nil)).To(MatchError(
				ContainSubstring("go/imex requires Options.OntologyImportPath"),
			))
		})
	})

	Describe("Generate", func() {
		It(
			"Should emit no files when no type declares the marker",
			func(ctx SpecContext) {
				source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
				}
			`
				resp := MustGenerate(ctx, source, "log", loader, p)
				Expect(resp.Files).To(BeEmpty())
			},
		)

		It(
			"Should emit the current version constant and Latest",
			func(ctx SpecContext) {
				source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
				resp := MustGenerate(ctx, source, "log", loader, p)
				Expect(resp.Files).To(HaveLen(3))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/v3/imex.gen.go",
				).ToContain(
					"// Code generated by oracle. DO NOT EDIT.",
					"package v3",
					`import "github.com/synnaxlabs/synnax/pkg/service/imex"`,
					"const Version imex.Version = 3",
				).
					ToBeValidGoSource()
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"package versions",
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions/v3"`,
					"const Latest = v3.Version",
					"func autoDecodeEnvelope(env imex.Envelope) (Log, error)",
					"case v3.Version:",
					"return imex.Decode[Log](env)",
				).
					ToBeValidGoSource()
				ExpectContent(resp, "core/pkg/service/log/imex.gen.go").ToContain(
					"package log",
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions"`,
					`"github.com/synnaxlabs/synnax/pkg/service/ontology"`,
					"func (s *Service) Export(ctx context.Context, id ontology.ID) "+
						"(imex.Envelope, error)",
					"var v Log",
					"Where(MatchKeys(key))",
					"Version: versions.Latest, Type: string(s.Type()), Name: v.Name,",
					"imex.Encode(&env, v)",
				).ToBeValidGoSource()
			},
		)

		It(
			"Should delete constants in version directories below the floor",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				diskLoader := NewMockFileLoaderWithRoot(tmpDir)
				for _, dir := range []string{"v2", "v3", "legacy", "testdata"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir,
							"core/pkg/service/log/versions",
							dir,
						),
						0o755,
					)).To(Succeed())
				}
				source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
				resp := MustGenerate(ctx, source, "log", diskLoader, p)
				Expect(resp.Files).To(HaveLen(3))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/v3/imex.gen.go",
				).ToContain(
					"package v3",
					"const Version imex.Version = 3",
				).
					ToBeValidGoSource()
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"const Latest = v3.Version",
				).
					ToBeValidGoSource()
				Expect(resp.Deletions).To(ConsistOf(
					"core/pkg/service/log/versions/v2/imex.gen.go",
				))
			},
		)

		It("Should derive packages from a nested output path", func(ctx SpecContext) {
			source := `
				@go output "core/pkg/service/schematic/symbol"

				Symbol struct {
					key  uuid
					name string
					@go version 1
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "symbol", loader, p)
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/v1/imex.gen.go",
			).ToContain(
				"package v1",
				"const Version imex.Version = 1",
			).ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/versions/imex.gen.go",
			).ToContain(
				"package versions",
				`"github.com/synnaxlabs/synnax/core/pkg/service/schematic/symbol/versions/v1"`,
				"const Latest = v1.Version",
			).
				ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/schematic/symbol/imex.gen.go",
			).ToContain(
				"package symbol",
				`"github.com/synnaxlabs/synnax/core/pkg/service/schematic/symbol/versions"`,
				"var v Symbol",
			).
				ToBeValidGoSource()
		})

		It(
			"Should extend the ladder back to the first snapshot carrying the marker",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				diskLoader := NewMockFileLoaderWithRoot(tmpDir)
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir,
							"core/pkg/service/log/versions",
							dir,
						),
						0o755,
					)).To(Succeed())
				}
				Expect(os.WriteFile(
					filepath.Join(
						tmpDir,
						"core/pkg/service/log/versions/v3/migrate.go",
					),
					[]byte("package v3\n\nfunc MigrateLog() {}\n"),
					0o644,
				)).To(Succeed())
				snapshot := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 2
					@go imex
				}
			`, "log", diskLoader)
				req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`, "log", diskLoader)
				req.SnapshotVersion = 1
				req.LoadSnapshot = func(int) (*resolution.Table, error) {
					return snapshot.Resolutions, nil
				}
				resp := MustSucceed(p.Generate(req))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					`"github.com/synnaxlabs/synnax/core/pkg/service/log/versions/v2"`,
					"func autoDecodeEnvelope(env imex.Envelope) (Log, error)",
					"case v2.Version:",
					"t2, err := imex.Decode[v2.Log](env)",
					"t3, err := v3.MigrateLog(t2)",
					"return t3, nil",
				).
					ToBeValidGoSource()
			},
		)

		It(
			"Should pass alias-only bumps through without a migrate step",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				diskLoader := NewMockFileLoaderWithRoot(tmpDir)
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(
							tmpDir,
							"core/pkg/service/log/versions",
							dir,
						),
						0o755,
					)).To(Succeed())
				}
				snapshot := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 2
					@go imex
				}
			`, "log", diskLoader)
				req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`, "log", diskLoader)
				req.SnapshotVersion = 1
				req.LoadSnapshot = func(int) (*resolution.Table, error) {
					return snapshot.Resolutions, nil
				}
				resp := MustSucceed(p.Generate(req))
				ExpectContent(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				).ToContain(
					"func autoDecodeEnvelope(env imex.Envelope) (Log, error)",
					"case v2.Version:",
					"t2, err := imex.Decode[v2.Log](env)",
					"return t2, nil",
				).
					ToBeValidGoSource()
			},
		)

		It(
			"Should floor at the current version when snapshots lack the marker",
			func(ctx SpecContext) {
				snapshot := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 2
				}
			`, "log", loader)
				req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`, "log", loader)
				req.SnapshotVersion = 1
				req.LoadSnapshot = func(int) (*resolution.Table, error) {
					return snapshot.Resolutions, nil
				}
				resp := MustSucceed(p.Generate(req))
				content := MustContentOf(
					resp,
					"core/pkg/service/log/versions/imex.gen.go",
				)
				Expect(content).To(ContainSubstring("const Latest = v3.Version"))
				Expect(content).ToNot(ContainSubstring("case v2.Version:"))
			},
		)

		It("Should import the configured runtime package", func(ctx SpecContext) {
			custom := imex.New(imex.Options{
				FileNamePattern:   "imex.gen.go",
				RuntimeImportPath: "github.com/acme/portable/imex",
			})
			source := `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`
			resp := MustGenerate(ctx, source, "log", loader, custom)
			ExpectContent(
				resp, "core/pkg/service/log/versions/v3/imex.gen.go",
			).ToContain(`import "github.com/acme/portable/imex"`).ToBeValidGoSource()
			ExpectContent(
				resp, "core/pkg/service/log/versions/imex.gen.go",
			).ToContain(`"github.com/acme/portable/imex"`).ToBeValidGoSource()
		})

		It("Should floor at the current version when a snapshot fails to load", func(
			ctx SpecContext,
		) {
			req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`, "log", loader)
			req.SnapshotVersion = 1
			req.LoadSnapshot = func(int) (*resolution.Table, error) {
				return nil, errors.New("snapshot on fire")
			}
			resp := MustSucceed(p.Generate(req))
			content := MustContentOf(
				resp,
				"core/pkg/service/log/versions/imex.gen.go",
			)
			Expect(content).To(ContainSubstring("const Latest = v3.Version"))
			Expect(content).ToNot(ContainSubstring("case v2.Version:"))
		})

		It(
			"Should error when a version package does not parse",
			func(ctx SpecContext) {
				tmpDir := GinkgoT().TempDir()
				diskLoader := NewMockFileLoaderWithRoot(tmpDir)
				for _, dir := range []string{"v2", "v3"} {
					Expect(os.MkdirAll(
						filepath.Join(tmpDir, "core/pkg/service/log/versions", dir),
						0o755,
					)).To(Succeed())
				}
				Expect(os.WriteFile(
					filepath.Join(
						tmpDir, "core/pkg/service/log/versions/v3/migrate.go",
					),
					[]byte("package v3\n\nfunc MigrateLog( {\n"),
					0o644,
				)).To(Succeed())
				snapshot := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 2
					@go imex
				}
			`, "log", diskLoader)
				req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/log"

				Log struct {
					key  uuid
					name string
					@go version 3
					@go imex
				}
			`, "log", diskLoader)
				req.SnapshotVersion = 1
				req.LoadSnapshot = func(int) (*resolution.Table, error) {
					return snapshot.Resolutions, nil
				}
				Expect(p.Generate(req)).Error().To(MatchError(
					ContainSubstring("versions/v3/migrate.go"),
				))
			},
		)

		It(
			"Should error when two types at one path both declare the marker",
			func(ctx SpecContext) {
				source := `
				@go output "core/pkg/service/log"

				Log struct {
					key uuid
					@go version 3
					@go imex
				}

				Sibling struct {
					key uuid
					@go version 3
					@go imex
				}
			`
				req := MustGenerateRequest(ctx, source, "log", loader)
				Expect(p.Generate(req)).Error().To(MatchError(
					ContainSubstring("duplicate @go imex declarations"),
				))
			},
		)
	})
})
