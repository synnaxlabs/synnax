package actions_test

import (
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"github.com/synnaxlabs/oracle/plugin/go/actions"
	. "github.com/synnaxlabs/oracle/testutil"
	. "github.com/synnaxlabs/x/testutil"
)

func TestGoActions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Plugin Go Actions Suite", SuiteConfig())
}

var _ = Describe("Go Actions Plugin", func() {
	var (
		loader *MockFileLoader
		p      *actions.Plugin
	)

	BeforeEach(func() {
		loader = NewMockFileLoader()
		p = actions.New(actions.DefaultOptions())
	})

	Describe("Plugin Interface", func() {
		It("Should have correct name", func() {
			Expect(p.Name()).To(Equal("go/actions"))
		})

		It("Should filter on go domain", func() {
			Expect(p.Domains()).To(Equal([]string{"go"}))
		})

		It("Should require go/types", func() {
			Expect(p.Requires()).To(Equal([]string{"go/types"}))
		})
	})

	Describe("Generate", func() {
		Context("structs without actions", func() {
			It("Should emit no files", func(ctx SpecContext) {
				source := `
					@go output "core/pkg/service/user"

					User struct {
						key  uuid
						name string
					}
				`
				resp := MustGenerate(ctx, source, "user", loader, p)
				Expect(resp.Files).To(BeEmpty())
			})
		})

		Context("unions with actions", func() {
			It("Should emit actions that reduce the union", func(ctx SpecContext) {
				source := `
					@go output "core/pkg/service/shape"

					Base struct {
						key  uuid
						name string
					}

					Shape union on type extends Base {
						circle {
							radius float64
						}
						square {}

						action Rename {
							name string
						}
					}
				`
				resp := MustGenerate(ctx, source, "shape", loader, p)
				Expect(resp.Files).To(HaveLen(1))
				ExpectContent(resp, "actions.gen.go").ToBeValidGoSource().ToContain(
					"package shape",
					"func Reduce(state Shape, acts ...Action) (Shape, error) {",
					"case RenamePayload:\n\t\t\tstate, err = v.Handle(state)",
					"func NewRenameAction(p RenamePayload) Action "+
						"{ return Action{Variant: p} }",
				)
			})
		})

		Context("structs with actions", func() {
			It("Should switch on the variant of each action", func(ctx SpecContext) {
				source := `
					@go output "core/pkg/service/counter"

					Counter struct {
						key   uuid
						value int32

						action SetValue {
							value int32
						}

						action Increment {}
					}
				`
				resp := MustGenerate(ctx, source, "counter", loader, p)
				Expect(resp.Files).To(HaveLen(1))
				ExpectContent(resp, "actions.gen.go").
					ToBeValidGoSource().
					ToContain(
						"// Code generated by oracle. DO NOT EDIT.",
						"package counter",
						`"github.com/synnaxlabs/x/errors"`,
						`"github.com/synnaxlabs/x/union"`,
						"func Reduce(state Counter, acts ...Action) (Counter, error) {",
						"switch v := a.Variant.(type) {",
						"case SetValuePayload:",
						"case IncrementPayload:",
						"case nil:\n\t\t\treturn state, union.ErrMissingPayload",
						`return state, errors.Newf("Action: unknown variant %T", v)`,
						"func NewSetValueAction(p SetValuePayload) Action",
						"func NewIncrementAction(p IncrementPayload) Action",
					).
					ToNotContain("func ReduceAll", "pkg/service/actions")
			})

			It(
				"Should reject the payload that only the Core emits",
				func(ctx SpecContext) {
					loader.Add("schemas/x/patch", `
						@go output "x/go/patch"

						Set struct { path string[] }
						Remove struct { path string[] }
						Insert struct { path string[] }
						Move struct { path string[] }
					`)
					source := `
					import "schemas/x/patch"

					@go output "core/pkg/service/counter"

					Counter struct {
						key uuid

						@actions
					}
				`
					resp := MustGenerate(ctx, source, "counter", loader, p)
					ExpectContent(resp, "actions.gen.go").
						ToBeValidGoSource().
						ToContain(
							`"github.com/synnaxlabs/synnax/pkg/service/actions"`,
							"func (CreatePayload) Handle(Counter) (Counter, error) {\n"+
								"\treturn Counter{}, actions.ErrCoreOnly\n}",
							"case CreatePayload:",
							"case SetPayload:",
							"case MovePayload:",
							"func NewCreateAction(p CreatePayload) Action",
							"func NewSetAction(p SetPayload) Action",
						).
						ToNotContain("func (SetPayload) Handle")
				},
			)

			It(
				"Should apply the update and check its Core-only fields",
				func(ctx SpecContext) {
					loader.Add("schemas/x/patch", `
						@go output "x/go/patch"

						Set struct { path string[] }
						Remove struct { path string[] }
						Insert struct { path string[] }
						Move struct { path string[] }
						Change struct<T> {
							value T?
							@presence
						}
						Update struct<V> { value V }
					`)
					source := `
					import "schemas/x/patch"

					@go output "core/pkg/service/counter"

					Counter struct {
						key  uuid
						name string  { @patch }
						hash string  { @patch core }
						note string? { @patch core }

						@actions
					}
				`
					resp := MustGenerate(ctx, source, "counter", loader, p)
					ExpectContent(resp, "actions.gen.go").
						ToBeValidGoSource().
						ToContain(
							`"github.com/synnaxlabs/x/patch"`,
							"func (p UpdatePayload) Handle(r Counter) "+
								"(Counter, error) {\n"+
								"\tu := patch.Update[Update](p)\n"+
								"\tif err := u.Check(r); err != nil {\n"+
								"\t\treturn r, err\n\t}\n"+
								"\tnext := r\n"+
								"\tif err := u.Value.ApplyTo(&next); err != nil {\n"+
								"\t\treturn r, err\n\t}\n"+
								"\treturn next, nil\n}",
							"func (p UpdatePayload) CheckCoreOnly() error {\n"+
								"\tif p.Value.Hash != nil {\n"+
								"\t\treturn errors.Mark(\n"+
								"\t\t\terrors.Wrap(validate.ErrValidation, "+
								"\"hash is set by the Core\"),\n"+
								"\t\t\tactions.ErrCoreOnly,\n\t\t)\n\t}\n"+
								"\tif !p.Value.Note.IsZero() {\n"+
								"\t\treturn errors.Mark(\n"+
								"\t\t\terrors.Wrap(validate.ErrValidation, "+
								"\"note is set by the Core\"),\n"+
								"\t\t\tactions.ErrCoreOnly,\n\t\t)\n\t}\n"+
								"\treturn nil\n}",
							"case UpdatePayload:\n\t\t\tstate, err = v.Handle(state)",
						)
				},
			)

			It(
				"Should reduce a generic struct with any for each kept type parameter",
				func(ctx SpecContext) {
					source := `
					@go output "core/pkg/service/report"

					Report struct<Details?, Extra?, Kind extends string = string> {
						key     uuid
						details Details
						extra   Extra
						kind    Kind

						action Set {
							report Report<any, any>
						}
					}
				`
					resp := MustGenerate(ctx, source, "report", loader, p)
					ExpectContent(resp, "actions.gen.go").ToContain(
						"func Reduce(state Report[any, any], acts ...Action) " +
							"(Report[any, any], error) {",
					)
				},
			)

			It(
				"Should name the constructor of a multi-word action in Pascal case",
				func(ctx SpecContext) {
					source := `
					@go output "core/pkg/service/board"

					Board struct {
						key uuid

						action SetNodePosition {
							key string
						}
					}
				`
					resp := MustGenerate(ctx, source, "board", loader, p)
					ExpectContent(resp, "actions.gen.go").ToContain(
						"func NewSetNodePositionAction(p SetNodePositionPayload) Action",
					)
				},
			)
		})

		It("Should require a runtime import path", func(ctx SpecContext) {
			req := MustGenerateRequest(ctx, `
				@go output "core/pkg/service/board"

				Board struct {
					key uuid

					action Clear {}
				}
			`, "board", loader)
			Expect(actions.New(actions.Options{FileNamePattern: "actions.gen.go"}).
				Generate(req)).Error().
				To(MatchError("go/actions requires Options.RuntimeImportPath"))
		})
	})
})

var _ = ShouldNotLeakGoroutinesPerSpec()
