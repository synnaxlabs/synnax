// Package actions generates a discriminated-union action codec for any oracle
// struct that declares one or more actions. Each action becomes a payload type
// with JSON+msgpack tags, an Action envelope dispatches by Type, and a variadic
// Reduce applies one or more actions sequentially to the target struct value.
// Per-action behavior (the Handle method on each payload type) is hand-written
// in a sibling file and is not generated by this plugin.
package actions

import (
	"bytes"
	"strings"
	"text/template"

	"github.com/synnaxlabs/oracle/domain/doc"
	"github.com/synnaxlabs/oracle/exec"
	"github.com/synnaxlabs/oracle/plugin"
	"github.com/synnaxlabs/oracle/plugin/go/internal/imports"
	"github.com/synnaxlabs/oracle/plugin/go/internal/naming"
	goprimitives "github.com/synnaxlabs/oracle/plugin/go/primitives"
	gotypes "github.com/synnaxlabs/oracle/plugin/go/types"
	"github.com/synnaxlabs/oracle/plugin/internal/casing"
	"github.com/synnaxlabs/oracle/plugin/output"
	"github.com/synnaxlabs/oracle/plugin/resolver"
	"github.com/synnaxlabs/oracle/resolution"
)

// Options configures the actions plugin output.
type Options struct {
	// FileNamePattern is the basename written for each output package.
	FileNamePattern string
}

// DefaultOptions returns the production defaults: actions.gen.go.
func DefaultOptions() Options {
	return Options{FileNamePattern: "actions.gen.go"}
}

// Plugin emits the generated action codec.
type Plugin struct{ options Options }

// New constructs a Plugin with the given options.
func New(opts Options) *Plugin { return &Plugin{options: opts} }

func (*Plugin) Name() string                  { return "go/actions" }
func (*Plugin) Domains() []string             { return []string{"go"} }
func (*Plugin) Requires() []string            { return []string{"go/types"} }
func (*Plugin) Check(_ *plugin.Request) error { return nil }

var goPostWriter = &exec.PostWriter{
	Extensions: []string{".go"},
	Commands:   [][]string{{"gofmt", "-w"}},
}

// PostWrite runs gofmt on the generated files.
func (*Plugin) PostWrite(files []string) error {
	return goPostWriter.PostWrite(files)
}

// Generate emits one actions.gen.go per output package containing structs that
// declare actions. Structs without actions are skipped.
func (p *Plugin) Generate(req *plugin.Request) (*plugin.Response, error) {
	resp := &plugin.Response{}
	for _, typ := range req.Resolutions.StructTypes() {
		form, ok := typ.Form.(resolution.StructForm)
		if !ok || len(form.Actions) == 0 {
			continue
		}
		outputPath := output.GetPath(typ, "go")
		if outputPath == "" {
			continue
		}
		content, err := p.generateFile(typ, form, outputPath, req)
		if err != nil {
			return nil, err
		}
		resp.Files = append(resp.Files, plugin.File{
			Path:    outputPath + "/" + p.options.FileNamePattern,
			Content: content,
		})
	}
	return resp, nil
}

func (*Plugin) generateFile(
	typ resolution.Type,
	form resolution.StructForm,
	outputPath string,
	req *plugin.Request,
) ([]byte, error) {
	pkg := naming.DerivePackageName(outputPath)
	mgr := imports.NewManager()
	ctx := &resolver.Context{
		Table:                         req.Resolutions,
		OutputPath:                    outputPath,
		Namespace:                     typ.Namespace,
		RepoRoot:                      req.RepoRoot,
		DomainName:                    "go",
		SubstituteDefaultedTypeParams: true,
	}
	r := &resolver.Resolver{
		Formatter: gotypes.GoFormatter(),
		ImportResolver: &gotypes.GoImportResolver{
			RepoRoot:       req.RepoRoot,
			CurrentPackage: pkg,
		},
		ImportAdder:     mgr,
		PrimitiveMapper: goprimitives.Mapper(),
	}

	data := templateData{
		Package:    pkg,
		TargetType: naming.GetGoName(typ),
		imports:    mgr,
	}

	for _, action := range form.Actions {
		ad := actionData{
			Name:     naming.ToPascalCase(action.Name),
			TypeName: casing.TypeSnake(action.Name),
			Doc:      doc.Get(action.Domains),
		}
		for _, field := range action.Fields {
			ad.Fields = append(ad.Fields, processField(field, r, ctx))
		}
		data.Actions = append(data.Actions, ad)
	}

	if len(data.Actions) > 0 {
		mgr.AddExternal("github.com/synnaxlabs/x/union")
	}

	var buf bytes.Buffer
	if err := fileTemplate.Execute(&buf, &data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// processField mirrors gotypes' optionality handling: optional values get a
// pointer prefix only when the underlying type is not already a slice, map, or
// msgpack.EncodedJSON (which carry their own nil semantics).
func processField(
	field resolution.Field,
	r *resolver.Resolver,
	ctx *resolver.Context,
) fieldData {
	goType := r.ResolveTypeRef(field.Type, ctx)
	if field.Optional &&
		!strings.HasPrefix(goType, "[]") &&
		!strings.HasPrefix(goType, "map[") &&
		!strings.HasPrefix(goType, "msgpack.EncodedJSON") {
		goType = "*" + goType
	}
	return fieldData{
		GoName:     naming.GetFieldName(field),
		GoType:     goType,
		JSONName:   casing.FieldSnake(field.Name),
		IsOptional: field.Optional,
	}
}

type templateData struct {
	Package    string
	TargetType string
	Actions    []actionData
	imports    *imports.Manager
}

func (d *templateData) HasImports() bool          { return d.imports.HasImports() }
func (d *templateData) ExternalImports() []string { return d.imports.ExternalImports() }
func (d *templateData) InternalImports() []imports.InternalImportData {
	return d.imports.InternalImports()
}

type actionData struct {
	Name     string
	TypeName string
	Doc      string
	Fields   []fieldData
}

type fieldData struct {
	GoName     string
	GoType     string
	JSONName   string
	IsOptional bool
}

// TagSuffix returns the JSON/msgpack tag suffix that controls omitempty
// emission for optional fields.
func (f fieldData) TagSuffix() string {
	if f.IsOptional {
		return ",omitempty"
	}
	return ""
}

var templateFuncs = template.FuncMap{
	"formatDoc": doc.FormatGo,
}

var fileTemplate = template.Must(
	template.New("go-actions").
		Funcs(templateFuncs).
		Parse(`// Code generated by oracle. DO NOT EDIT.

package {{.Package}}
{{- if .HasImports}}

import (
{{- range .ExternalImports}}
	"{{.}}"
{{- end}}
{{- range .InternalImports}}
{{- if .NeedsAlias}}
	{{.Alias}} "{{.Path}}"
{{- else}}
	"{{.Path}}"
{{- end}}
{{- end}}
)
{{- end}}

const (
{{- range .Actions}}
	ActionType{{.Name}} = "{{.TypeName}}"
{{- end}}
)
{{range .Actions}}
{{- if .Doc}}
{{formatDoc (printf "%sPayload" .Name) .Doc}}
{{end -}}
type {{.Name}}Payload struct {
{{- range .Fields}}
	{{.GoName}} {{.GoType}} ` + "`" + `json:"{{.JSONName}}{{.TagSuffix}}" msgpack:"{{.JSONName}}{{.TagSuffix}}"` + "`" + `
{{- end}}
}
{{end}}
// Action is a discriminated union for all {{.TargetType}} mutations. Type names
// the variant; the matching pointer field carries the payload and others are nil.
type Action struct {
	Type string ` + "`" + `json:"type" msgpack:"type"` + "`" + `
{{- range .Actions}}
	{{.Name}} *{{.Name}}Payload ` + "`" + `json:"{{.TypeName}},omitempty" msgpack:"{{.TypeName}},omitempty"` + "`" + `
{{- end}}
}

// Reduce applies the given actions sequentially to state by dispatching on
// each action's Type to the matching payload's Handle method. Unknown action
// types leave state unchanged. An action whose Type names a known variant but
// carries a nil payload pointer returns an error. Returns the first error
// encountered along with the partially-reduced state.
func Reduce(state {{.TargetType}}, actions ...Action) ({{.TargetType}}, error) {
	var err error
	for _, a := range actions {
		switch a.Type {
{{- range .Actions}}
		case ActionType{{.Name}}:
			if a.{{.Name}} == nil {
				return state, union.MissingPayload(a.Type)
			}
			state, err = a.{{.Name}}.Handle(state)
{{- end}}
		default:
			continue
		}
		if err != nil {
			return state, err
		}
	}
	return state, nil
}
{{range .Actions}}
// New{{.Name}}Action wraps a {{.Name}}Payload in an Action envelope.
func New{{.Name}}Action(p {{.Name}}Payload) Action {
	return Action{Type: ActionType{{.Name}}, {{.Name}}: &p}
}
{{end -}}
`),
)
