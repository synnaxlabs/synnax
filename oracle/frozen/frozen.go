// Package frozen records what each version package generated. `oracle sync` writes one
// sum file per chain, and the `frozen` gate of `oracle check` compares it to the disk,
// so a frozen package cannot change while its schema stands still.
package frozen

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/synnaxlabs/oracle/paths"
	"github.com/synnaxlabs/oracle/pipeline"
	"github.com/synnaxlabs/oracle/plugin"
	gotypes "github.com/synnaxlabs/oracle/plugin/go/types"
	"github.com/synnaxlabs/x/errors"
)

const header = "# Code generated by oracle. DO NOT EDIT.\n"

// Sum identifies one version package at one point in time.
type Sum struct {
	// Schema hashes the chain's version files up to and including the version.
	Schema string
	// Output hashes the package's generated files as they stand on disk.
	Output string
}

// Chain holds the sums of one version chain's packages.
type Chain struct {
	// Path is the repo-relative path of the chain's sum file.
	Path string
	// Root is the repo-relative Go directory that holds versions/vN.
	Root string
	// Current is the first version that is not frozen.
	Current int
	// Sums holds the sums the workspace produces now, keyed by version.
	Sums map[int]Sum
}

// Package returns the repo-relative directory of version n.
func (c Chain) Package(n int) string {
	return path.Join(c.Root, paths.VersionsDirName, fmt.Sprintf("v%d", n))
}

// Moved reports whether frozen version n no longer matches its recorded sum while its
// version files stand still. A package that stopped generating counts as moved.
func (c Chain) Moved(n int, recorded Sum) bool {
	if n >= c.Current {
		return false
	}
	sum, ok := c.Sums[n]
	return !ok || (sum.Schema == recorded.Schema && sum.Output != recorded.Output)
}

// Versions returns every version in c.Sums or recorded, ascending.
func (c Chain) Versions(recorded map[int]Sum) []int {
	merged := maps.Clone(c.Sums)
	maps.Copy(merged, recorded)
	return slices.Sorted(maps.Keys(merged))
}

// Compute returns the current sums of every chain with a Go output, ordered by path. It
// reads generated files from disk, so it sees a hand edit that res does not hold.
func Compute(
	ctx context.Context, res *pipeline.Result, repoRoot string,
) ([]Chain, error) {
	roots, err := gotypes.ChainPaths(ctx, &plugin.Request{
		Resolutions: res.Resolutions, Versions: res.Versions,
	})
	if err != nil {
		return nil, err
	}
	outputs := make(map[string][]string)
	for _, files := range res.Outputs {
		for _, f := range files {
			dir := path.Dir(f.Path)
			outputs[dir] = append(outputs[dir], f.Path)
		}
	}
	chains := make([]Chain, 0, len(roots))
	for _, root := range slices.Sorted(maps.Keys(roots)) {
		cp := roots[root]
		c := Chain{
			Path:    sumPath(cp.LivePath),
			Root:    root,
			Current: cp.Current,
			Sums:    make(map[int]Sum, len(cp.Numbers)),
		}
		schema := sha256.New()
		for _, n := range cp.Numbers {
			source := res.Versions.Chains()[cp.LivePath].FilePath(n) + ".oracle"
			b, err := os.ReadFile(paths.Resolve(source, repoRoot))
			if err != nil {
				return nil, err
			}
			schema.Write(b)
			files := outputs[c.Package(n)]
			if len(files) == 0 {
				continue
			}
			output, err := hashFiles(files, repoRoot)
			if err != nil {
				return nil, err
			}
			c.Sums[n] = Sum{
				Schema: hex.EncodeToString(schema.Sum(nil)),
				Output: output,
			}
		}
		chains = append(chains, c)
	}
	return chains, nil
}

// sumPath maps a live path ("schemas/x/telem") to its sum file.
func sumPath(livePath string) string {
	return path.Join(path.Dir(livePath), "frozen", path.Base(livePath)+".sum")
}

// hashFiles hashes files by name and content. A missing file adds nothing, so its
// absence changes the result.
func hashFiles(files []string, repoRoot string) (string, error) {
	h := sha256.New()
	for _, f := range slices.Sorted(slices.Values(files)) {
		b, err := os.ReadFile(paths.Resolve(f, repoRoot))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return "", err
		}
		h.Write([]byte(path.Base(f) + "\x00"))
		h.Write(b)
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// Read returns the sums recorded in the sum file at the repo-relative path. A missing
// file holds no sums.
func Read(sumFile, repoRoot string) (map[int]Sum, error) {
	b, err := os.ReadFile(paths.Resolve(sumFile, repoRoot))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	sums := make(map[int]Sum)
	for line := range strings.Lines(string(b)) {
		if strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 3 {
			return nil, errors.Newf("%s: malformed line %q", sumFile, line)
		}
		n, err := strconv.Atoi(strings.TrimPrefix(fields[0], "v"))
		if err != nil {
			return nil, errors.Wrapf(err, "%s: malformed version", sumFile)
		}
		sums[n] = Sum{Schema: fields[1], Output: fields[2]}
	}
	return sums, nil
}

// Update rewrites the sum file of every chain. A frozen package whose schema did not
// change keeps its recorded sum, so the `frozen` gate reports the change. With refreeze
// set, it takes the new sum instead.
func Update(chains []Chain, repoRoot string, refreeze bool) error {
	for _, c := range chains {
		recorded, err := Read(c.Path, repoRoot)
		if err != nil {
			return err
		}
		var b strings.Builder
		b.WriteString(header)
		for _, n := range c.Versions(recorded) {
			sum, current := c.Sums[n]
			if old, ok := recorded[n]; ok && !refreeze && c.Moved(n, old) {
				sum, current = old, true
			}
			if current {
				fmt.Fprintf(&b, "v%d %s %s\n", n, sum.Schema, sum.Output)
			}
		}
		abs := paths.Resolve(c.Path, repoRoot)
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			return err
		}
		existing, err := os.ReadFile(abs)
		if err == nil && string(existing) == b.String() {
			continue
		}
		if err := os.WriteFile(abs, []byte(b.String()), 0o644); err != nil {
			return err
		}
	}
	return nil
}
